# Builds the card code loader image linked at BASE: $OUT/cl.bin (+ .elf, .map).  usage: build_cl.sh BASE   (BASE = final RAM address of its first byte)
set -euo pipefail
d=$(cd "$(dirname "$0")" && pwd); root=$(cd "$d/../../.." && pwd)
base="${1:?base address}"
P="${PPC_PREFIX:-/opt/devkitpro/devkitPPC/bin/powerpc-eabi}"
. "$root/offline/lr_safety.sh"
out="${OUT:-$root/build/offline/cardpkg/cl}"; mkdir -p "$out"
FLAGS=(-Os -mcpu=750 -ffreestanding -fno-builtin -msdata=none -fno-pic -msoft-float -fno-common -fno-tree-loop-distribute-patterns
  -fno-asynchronous-unwind-tables -ffunction-sections -fdata-sections -fno-stack-protector "${LR_CFLAGS[@]}")
[[ "${CL_LAYOUT:-}" == low ]] && FLAGS+=(-DCL_LIST_BASE=0x817C0000u)
[[ "${CL_LAYOUT:-}" == generic ]] && FLAGS+=(-DCL_LAYOUT_GENERIC)
[[ "${CL_COMP:-0}" == 1 ]] && FLAGS+=(-DCL_COMP=1)   # compressed code files (MSCF v2): MSLZ decoder + nibble CRC; unset = the loader without them
[[ -n "${CL_TEST:-}" ]] && FLAGS+=("-DCL_TEST=$CL_TEST")   # diagnostic builds only (see cl_loader.c)
[[ -n "${CL_CHUNK:-}" ]] && FLAGS+=("-DCL_CHUNK=${CL_CHUNK}u")   # diagnostic: blocks per CARDRead
[[ -n "${CL_PARTS:-}" ]] && FLAGS+=(-DCL_PARTS)   # split code files MultishineCodeP1..
[[ -n "${CL_DELAY:-}" ]] && FLAGS+=("-DCL_DELAY=${CL_DELAY}u")   # diagnostic: retraces between chunk reads
[[ -n "${CL_TRIES:-}" ]] && FLAGS+=("-DCL_TRIES=${CL_TRIES}u")   # verifying loader: boot-attempt limit of the automatic rollback (default 3, 0 = off)
[[ -n "${CL_SAFE:-}" ]] && FLAGS+=("-DCL_SAFE=${CL_SAFE}")       # verifying loader: L+R safe mode (default 1, 0 = off)
[[ -n "${CL_FILE_NAME:-}" ]] && FLAGS+=("-DCL_FILE_NAME=\"$CL_FILE_NAME\"")
[[ -n "${CL_MUTE:-}" ]] && FLAGS+=("-DCL_MUTE=${CL_MUTE}")         # verifying loader: music silent while it loads (default 1; 0 = the 1291 loader byte for byte)
OBJS=("$out/cl_entry.o" "$out/cl_loader.o")
# CL_VERIFY=release|dev: the OTA stage-0 loader.  release: pinned key(s) from CL_PUBKEY / CL_PUBKEY2 (64 hex each, REQUIRED, the public
# test key is refused); dev: the RFC 8032 test-1 public key (the matching private key is a published test vector) unless CL_PUBKEY is given, and unsigned files are accepted.
# Unset: the loader of byte for byte (no signature check).
# CL_KEYSET=prod: the RELEASE loader.  Pins PROD-A then PROD-B from tools/release/prod_pubkeys.txt (public keys, committed), CL_VERIFY=release, build_seq floor CL_MIN_SEQ default 1000.
# Unset (the default): nothing changes, the dev loader behaviour is untouched.  Explicit CL_PUBKEY/CL_PUBKEY2/CL_VERIFY together with CL_KEYSET are refused (no mixing).
if [[ "${CL_KEYSET:-}" == prod ]]; then
  [[ -z "${CL_PUBKEY:-}${CL_PUBKEY2:-}${CL_VERIFY:-}" ]] || { echo "CL_KEYSET=prod sets CL_VERIFY/CL_PUBKEY/CL_PUBKEY2 itself: unset them" >&2; exit 1; }
  pk="${CL_PROD_KEYS_FILE:-$root/tools/release/prod_pubkeys.txt}"
  CL_PUBKEY=$(awk '$1=="prod-a"{print $2}' "$pk"); CL_PUBKEY2=$(awk '$1=="prod-b"{print $2}' "$pk")
  [[ -n "$CL_PUBKEY" && -n "$CL_PUBKEY2" ]] || { echo "need prod-a and prod-b in $pk" >&2; exit 1; }
  CL_VERIFY=release; CL_MIN_SEQ="${CL_MIN_SEQ:-1000}"
elif [[ -n "${CL_KEYSET:-}" ]]; then echo "CL_KEYSET must be prod (or unset)" >&2; exit 1; fi
if [[ -n "${CL_VERIFY:-}" ]]; then
  TESTPUB=d75a980182b10ab7d54bfed3c964073a0ee172f3daa62325af021a68f707511a
  case "$CL_VERIFY" in
    release) [[ -n "${CL_PUBKEY:-}" ]] || { echo "CL_VERIFY=release needs CL_PUBKEY (64 hex)" >&2; exit 1; }
             [[ "$(echo "$CL_PUBKEY" | tr A-F a-f)" != "$TESTPUB" && "$(echo "${CL_PUBKEY2:-x}" | tr A-F a-f)" != "$TESTPUB" ]] || { echo "the public test key must never be pinned by a release loader" >&2; exit 1; }
             DEVF=0 ;;
    dev)     CL_PUBKEY="${CL_PUBKEY:-$TESTPUB}"; DEVF=1 ;;
    *) echo "CL_VERIFY must be release or dev" >&2; exit 1 ;;
  esac
  keys=("$CL_PUBKEY"); [[ -n "${CL_PUBKEY2:-}" ]] && keys+=("$CL_PUBKEY2")
  for k in "${keys[@]}"; do [[ "$k" =~ ^[0-9a-fA-F]{64}$ ]] || { echo "bad public key: need 64 hex" >&2; exit 1; }; done
  {
    echo "/* generated by build_cl.sh (CL_VERIFY=$CL_VERIFY): pinned Ed25519 public keys */"
    echo "#define CL_NKEYS ${#keys[@]}"
    echo "static const u8 cl_pub[CL_NKEYS][32] = {"
    for k in "${keys[@]}"; do printf '  {'; for ((i=0;i<64;i+=2)); do printf '0x%s,' "${k:$i:2}"; done; echo '},'; done
    echo "};"
  } > "$out/cl_keys.h"
  [[ -n "${CL_FILE_NAME:-}" ]] && FLAGS+=("-DCL_STATE_NAME=\"${CL_FILE_NAME%Code}State\"")
  FLAGS+=(-DCL_VERIFY=1 "-DCL_DEV=$DEVF" "-I$out" "-I$d" "-I$root/offline/client_net" ${CL_MIN_SEQ:+"-DCL_MIN_SEQ=${CL_MIN_SEQ}u"})
  C="$root/offline/client_net/mw2_crypto.c"
  "$P-gcc" "${FLAGS[@]}" -std=gnu99 -Wall -Wextra -fstack-usage -c "$C" -o "$out/mw2_crypto.o"
  OBJS+=("$out/mw2_crypto.o")
fi
# CL_SRC (full path) / CL_EXTRA_ASM (file names inside cl/, space separated): DIAGNOSTIC builds only. Unset = the loader exactly as before.
SRC="${CL_SRC:-$d/cl_loader.c}"; XW=(); [[ -n "${CL_SRC:-}" ]] && XW+=(-Wno-unused-function)
"$P-gcc" "${FLAGS[@]}" -std=gnu99 -Wall -Wextra -Werror ${XW[@]+"${XW[@]}"} -c "$SRC" -o "$out/cl_loader.o"
XO=(); for xa in ${CL_EXTRA_ASM:-}; do "$P-gcc" -mcpu=750 -c "$d/$xa" -o "$out/$(basename "$xa" .S).o"; OBJS+=("$out/$(basename "$xa" .S).o"); XO+=("$out/$(basename "$xa" .S).o"); done
if "$P-objdump" -d "$out/cl_loader.o" | grep -E '\s(lf[sd]|stf[sd]|fmr|fadd|fmul|fctiw|frsp)' >/dev/null; then echo "FPU instruction in cl_loader.o" >&2; exit 1; fi
"$P-gcc" -mcpu=750 -c "$d/cl_entry.S" -o "$out/cl_entry.o"
"$P-gcc" -nostartfiles -nostdlib -Wl,-T,"$d/cl.ld" -Wl,-Ttext="$base" -Wl,--gc-sections -Wl,-Map,"$out/cl.map" "${OBJS[@]}" -lgcc -o "$out/cl.elf"
"$P-objcopy" -O binary "$out/cl.elf" "$out/cl.bin"
"$P-nm" -u "$out/cl.elf" | grep . && { echo "unresolved symbols" >&2; exit 1; } || true
lr_check_libgcc "$out/cl.map" >&2
lr_check_c "$out/cl_loader.o" ${CL_VERIFY:+"$out/mw2_crypto.o"} >&2
lr_verify "$out/cl_entry.o" ${XO[@]+"${XO[@]}"} >&2
echo "image: $out/cl.bin ($(wc -c < "$out/cl.bin") bytes) base $base" >&2
