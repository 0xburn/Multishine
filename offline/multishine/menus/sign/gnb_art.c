static u8 *btex(unsigned v)
{
    u8 *base = (u8 *)((((u32)BTEX_RAW) + 31u) & ~31u);
#ifdef GNB_SETUP_ART
    if (v >= BV_GT) return (u8 *)((((u32)A.traw) + 31u) & ~31u) + GT_OFF[v - BV_GT];
#endif
    return v < BV_COV ? base + v * STB_RI_L_BYTES : base + BTEX_OFF_COV + (v - BV_COV) * (STB_TEX_SIZE * STB_TEX_SIZE);
}

static void *find_proc(u32 cb)
{
    void **heads = (void **)W(PLINK_HEAD);
    u32 n = (u32)B(GOBJ_INIT) + 1u, p;
    if (!heads) return 0;
    if (n > 64u) n = 64u;
    for (p = 0; p < n; p++) {
        u8 *go = (u8 *)heads[p];
        u32 guard = 0;
        while (go && guard++ < 4096u) {
            u8 *pr = (u8 *)W((u32)go + 0x18u);
            u32 g2 = 0;
            while (pr && g2++ < 64u) { if (W((u32)pr + 0x14u) == cb) return go; pr = (u8 *)W((u32)pr); }
            go = (u8 *)W((u32)go + 0x08u);
        }
    }
    return 0;
}

static int ok_ptr(u32 p) { return p >= 0x80000000u && p < 0x81800000u && !(p & 3u); }

/* HSD_Joint: +4 flags, +8 child, +C next, +10 dobj desc; HSD_DObjDesc: +4 next, +8 mobj desc; HSD_MObjDesc: +8 tobj desc; HSD_TObjDesc: +0x4C image desc;
   HSD_ImageDesc: +0 data, +4 w, +6 h, +8 format */
static u32 *dfs(u32 *j, unsigned want, unsigned *at)
{
    unsigned guard = 0;
    while (j && ok_ptr((u32)j) && guard++ < 256u) {
        u32 *r;
        if (*at == want) return j;
        (*at)++;
        if (W((u32)j + 8u) && (r = dfs((u32 *)W((u32)j + 8u), want, at)) != 0) return r;
        j = (u32 *)W((u32)j + 0xCu);
    }
    return 0;
}
static u32 *joint_at(u32 *root, unsigned idx) { unsigned at = 0; return dfs(root, idx, &at); }
static u32 dobj_n(u32 *j, unsigned n)               /* the n-th DObj desc of a joint */
{
    u32 d = W((u32)j + 0x10u);
    while (d && n--) d = W(d + 4u);
    return d;
}
static u32 image_of(u32 dobj, unsigned w, unsigned h, unsigned fmt)   /* the image desc of a DObj desc's first texture when it has this shape, else 0 */
{
    u32 m, t, i;
    if (!dobj || !ok_ptr(dobj) || !(m = W(dobj + 8u)) || !ok_ptr(m) || !(t = W(m + 8u)) || !ok_ptr(t) || !(i = W(t + 0x4Cu)) || !ok_ptr(i)) return 0;
    return H(i + 4u) == w && H(i + 6u) == h && W(i + 8u) == fmt ? i : 0;
}
static unsigned kids(u32 *j) { unsigned n = 0; u32 c = W((u32)j + 8u); while (c && n < 16u) { n++; c = W(c + 0xCu); } return n; }

static void *load(const char *base)
{
    char *full = FULLNAME(base);
    if (!full || ENTRYNUM(full) < 0) return 0;
    return ARC_LOAD(base, 0);
}

static void copy_desc(u32 *dst, const u32 *src) { unsigned i; for (i = 0; i < 16u; i++) dst[i] = src[i]; dst[3] = 0; }

/* GX texture sizes: tiled and padded to whole tiles (I4 8x8, I8 / IA4 8x4, IA8 4x4), so 168 x 28 I4 is 2688 bytes, not 2352; 0 for a format we do not know */
static u32 tex_bytes(u32 w, u32 h, u32 fmt)
{
    u32 bw, bh, bpp;
    switch (fmt) {
    case 0u: bw = 8u; bh = 8u; bpp = 4u; break;                 /* I4 */
    case 1u: bw = 8u; bh = 4u; bpp = 8u; break;                 /* I8 */
    case 2u: bw = 8u; bh = 4u; bpp = 8u; break;                 /* IA4 */
    case 3u: bw = 4u; bh = 4u; bpp = 16u; break;                /* IA8 */
    default: return 0;
    }
    return ((w + bw - 1u) / bw) * ((h + bh - 1u) / bh) * bw * bh * bpp / 8u;
}
/* the data of an image descriptor that image_of has recognised, when all `n` bytes of it (n = the texture's own padded size) lie inside RAM and the buffer is 32-aligned
   (GX reads texture data from nowhere else): else 0.  Every write of the art goes through this. */
static u8 *img_data(u32 img, u32 n)
{
    u32 d;
    if (!img || !ok_ptr(img) || !n) return 0;
    d = W(img);
    if (!ok_ptr(d) || (d & 31u) || n > 0x81800000u - d) return 0;
    return (u8 *)d;
}
static u32 img_n(u32 img) { return tex_bytes(H(img + 4u), H(img + 6u), W(img + 8u)); }
/* a label that could not be patched is blanked instead (transparent), never left as "Trophies" / "TROPHY LIST" */
static void blank_image(u32 img)
{
    u32 n = img_n(img), i;
    u8 *d = img_data(img, n);
    if (!d) return;
    for (i = 0; i < n; i++) d[i] = 0;
    DC_STORE(d, n);
}

