/* PackBits (tools/gnb_setup_art.py) unpacked into d: exactly n bytes from exactly pk_n, else 0 */
static int gt_unpack(u8 *d, u32 n, const u8 *pk, u32 pk_n)
{
    u32 o = 0, i = 0, k, h;
    while (i < pk_n && o < n) {
        h = pk[i++];
        if (h < 128u) { if (i + h + 1u > pk_n || o + h + 1u > n) return 0; for (k = 0; k <= h; k++) d[o++] = pk[i++]; }
        else { if (i >= pk_n || o + h - 126u > n) return 0; for (k = 0; k < h - 126u; k++) d[o++] = pk[i]; i++; }
    }
    return o == n && i == pk_n;
}
