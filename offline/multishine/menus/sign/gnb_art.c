unsigned gart_open(void)
{
    if (A.open) return A.have;
    {   u8 *b = (u8 *)&A; unsigned i; for (i = 0; i < sizeof A; i++) b[i] = 0; }
    A.open = 1;
    A.tou = load("GmTou1p");
    if (A.tou) {
        u32 sc = (u32)ARC_PUB(A.tou, "ScGamTour_scene_data"), sets, set, *j;
        if (sc && ok_ptr(sc) && (sets = W(sc)) && ok_ptr(sets) && (set = W(sets + 4u * TOU_SET_BOX)) && ok_ptr(set) && ok_ptr(W(set))) {
            j = joint_at((u32 *)W(set), TOU_BOX);
            if (j && (W((u32)j + 4u) & 0xEu) == 0xEu && kids(j) == 4u && image_of(dobj_n(j, 0), 16u, 16u, 2u)) {
                A.box_j = j;
                copy_desc(A.box_d, j);
                A.box_d[1] &= ~JOBJ_HIDDEN;
                A.box_d[9] = 0x3F800000u;                               /* scale y = 1.0f (the tournament screen opens the box from 0) */
                A.have |= 1u << GART_BOX;
            }
        }
    }
    if (A.tou) {   /* set 5: the animated background.  Shape: the root joint (flags 0x20000008) with two children, the second with a model of its own, an anim joint array; else it stays unused */
        u32 sc = (u32)ARC_PUB(A.tou, "ScGamTour_scene_data"), sets, set, *j, an;
        if (sc && ok_ptr(sc) && (sets = W(sc)) && ok_ptr(sets) && (set = W(sets + 4u * TOU_SET_BG)) && ok_ptr(set) && ok_ptr(W(set)) && (j = (u32 *)W(set)) &&
            W((u32)j + 4u) == 0x20000008u && kids(j) == 2u && ok_ptr(W((u32)j + 8u)) && ok_ptr(W(W((u32)j + 8u) + 0xCu)) && ok_ptr(W(W(W((u32)j + 8u) + 0xCu) + 0x10u)) &&
            (an = W(set + 4u)) && ok_ptr(an) && ok_ptr(W(an)))
            A.bg_d = (u32 *)set;
    }
    A.fig = load("TyMnView");
    if (A.fig) {
        u32 *root = (u32 *)ARC_PUB(A.fig, "ToyFigurePanel_Top_joint"), *b, *h, *s, *c = (u32 *)ARC_PUB(A.fig, "ToyFigureListCursor_Top_joint");
        if (root && ok_ptr((u32)root)) {
            h = joint_at(root, FIG_HEAD);
            b = joint_at(root, FIG_BUTTON);
            s = joint_at(root, FIG_SIDE);
            if (h && image_of(dobj_n(h, 0), 176u, 120u, 2u)) {
                u32 l1 = image_of(dobj_n(h, 1), 168u, 28u, 0u), l2 = image_of(dobj_n(h, 2), 168u, 28u, 0u), sl = s ? image_of(dobj_n(s, 0), 160u, 12u, 2u) : 0;
                A.fig_j = root;
                A.have |= 1u << GART_FRAME;
#ifdef GNB_ROOMS_ART
                /* Rooms' own header art in place of "Trophies" / "Gallery" / "TROPHY LIST" (same sizes and formats).  Every label is its own step, so one that fails never takes the others
                   down, and a label that cannot be patched is written in the menu font (headers) or blanked (side): no retail word is left standing */
                if (l1) {
                    int ok = patch_image(l1, GNB_RA_LEFT, (u32)sizeof GNB_RA_LEFT, GNB_RA_LEFT_N);
                    if (header_word(l1, "Game Night")) ok = 1;           /*: "Game Night / Rooms" in place of Rooms' "Online Play" */
                    else if (!ok) blank_image(l1);
                    if (ok) A.labels |= 1u;
                }
                if (l2) {
                    int ok = patch_image(l2, GNB_RA_RIGHT, (u32)sizeof GNB_RA_RIGHT, GNB_RA_RIGHT_N);
                    if (!ok) { blank_image(l2); ok = header_word(l2, "Rooms"); }
                    if (ok) A.labels |= 2u;
                }
                if (sl) {
                    if (!patch_image(sl, GNB_RA_SIDE, (u32)sizeof GNB_RA_SIDE, GNB_RA_SIDE_N)) blank_image(sl);
                    A.labels |= 4u;
                }
#else
                if (l1) blank_image(l1);                                 /* no Rooms art in this build: the words are drawn as text (gnb_ev.c list_art); the retail ones are blanked */
                if (l2) blank_image(l2);
                if (sl) blank_image(sl);
#endif
            }
            if (b && image_of(dobj_n(b, 0), 96u, 32u, 2u)) { A.btn_j = b; copy_desc(A.btn_d, b); A.have |= 1u << GART_BUTTON; }
        }
        if (c && ok_ptr((u32)c) && image_of(dobj_n(c, 0), 32u, 16u, 1u)) { A.cur_j = c; A.have |= 1u << GART_CURSOR; }
    }
    return A.have;
}

