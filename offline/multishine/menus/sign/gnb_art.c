#define TOU_SET_ICON 1u                          /* ScGamTour_scene_data jobj set 1 joint 1: one quad +-1.495 x +-1.495 units, a 32x32 CI4 texture with a 16-entry RGB5A3 */
#define TOU_ICON 1u                              /* palette, constant colour, translucent (GmTou1p, already loaded by gart_open): the portraits' quad */
#define FILE_SIZE ((u32 (*)(int))0x8001634Cu)    /* lbFile_8001634C(entry): the file's length */
#define FILE_READ ((void (*)(int, u32, u32, u32, int, int))0x800161C4u)   /* lbFile_800161C4(entry, file offset, dst, size, 0x21 main memory, prio): synchronous */
#define DC_INVAL ((fn_range)0x803447DCu)         /* DCInvalidateRange */
/* the descriptor copies after the 4 KB of pixels: joint 0x40, DObj 0x10, MObj 0x18, TObj 0x5C (+4), image 0x18, palette 0x10 */
#define IB_JOINT 0x1000u
#define IB_DOBJ 0x1040u
#define IB_MOBJ 0x1050u
#define IB_TOBJ 0x1068u
#define IB_IMG 0x10C8u
#define IB_TLUT 0x10E0u

static u32 *face_template(void)
{
    u32 sc, sets, set, *j, d, m, t, tl;
    if (A.face_tried) return A.face;
    A.face_tried = 1;
    A.fstep = 1;
    if (!A.tou) return 0;
    A.fstep = 2;
    sc = (u32)ARC_PUB(A.tou, "ScGamTour_scene_data");
    if (!sc || !ok_ptr(sc) || !(sets = W(sc)) || !ok_ptr(sets) || !(set = W(sets + 4u * TOU_SET_ICON)) || !ok_ptr(set) || !ok_ptr(W(set))) return 0;
    A.fstep = 3;
    if (!(j = joint_at((u32 *)W(set), TOU_ICON))) return 0;
    A.fstep = 4;
    d = dobj_n(j, 0);
    if (!image_of(d, 32u, 32u, 8u)) return 0;                                                          /* the 32x32 CI4 texture */
    A.fstep = 5;
    if (W(d + 4u) || !ok_ptr(W(d + 0xCu))) return 0;                                                  /* one DObj, a PObj */
    A.fstep = 6;
    m = W(d + 8u); t = W(m + 8u); tl = W(t + 0x50u);
    if (W(t + 4u)) return 0;                                                                           /* one TObj */
    A.fstep = 7;
    if (!tl || !ok_ptr(tl)) return 0;                                                                  /* with a palette */
    A.fstep = 8;
    A.face = j;
    return j;
}

static u32 fnv(const u8 *p, u32 n) { u32 h = 0x811C9DC5u; while (n--) { h ^= *p++; h *= 0x01000193u; } return h; }
static void cpy(u8 *d, const u8 *s, u32 n) { while (n--) *d++ = *s++; }

/* Sheik's copy of Zelda's icon (the pixel block is ours: one 4 KB buffer per character): the caption strip (the bottom rows, x 4..59) painted with a dark palette entry that no pixel of the icon uses.
   CI8 64 x 56 in 8 x 4 tiles: pixel (x, y) at ((y / 4) * 8 + x / 8) * 32 + (y % 4) * 8 + x % 8 */
#ifdef GNB_SHEIK_DELTA
#include "gnb_sheik_delta.h"   /* GNB_SD[GNB_SD_N]: PackBits of (Sheik's icon block XOR the retail Zelda block), GNB_SD_SUM its FNV (tools/gnb_sheik_delta.py, build time only) */
#endif
/* Sheik's own icon ("we only ship the delta"): b holds Zelda's retail block (its FNV was checked on load); XOR the unpacked delta into it and check the
   result.  1 = b is now Sheik's icon (its own SHEIK strip: the cell draws no caption), 0 = no delta in this build or a mismatch (b restored to Zelda's) */
static int sheik_patch(u8 *b)
{
#ifdef GNB_SHEIK_DELTA
    u32 i = 0, o = 0, k, pass;
    for (pass = 0; pass < 2u; pass++) {
        i = 0; o = 0;
        while (o < CSS_BLOCK && i < GNB_SD_N) {
            u32 h = GNB_SD[i++];
            if (h < 128u) { for (k = 0; k <= h && o < CSS_BLOCK && i < GNB_SD_N; k++) b[o++] ^= GNB_SD[i++]; }
            else { for (k = 0; k < h - 126u && o < CSS_BLOCK; k++) b[o++] ^= GNB_SD[i]; i++; }
        }
        if (pass == 0u && fnv(b, CSS_BLOCK) == GNB_SD_SUM) { A.sheik = 1; return 1; }
    }                                                                       /* second pass: XOR again = Zelda's block back */
#else
    (void)b;
#endif
    return 0;
}
int gart_sheik_own(void) { return A.sheik; }

static void blank_caption(u8 *b)
{
    unsigned x, y, i, use[256 / 32], idx = 256u;
    for (i = 0; i < 256u / 32u; i++) use[i] = 0;
    for (i = 0; i < 64u * 56u; i++) use[b[i] >> 5] |= 1u << (b[i] & 31u);
    for (i = 255u; i > 0u; i--) if (!(use[i >> 5] & (1u << (i & 31u)))) { idx = i; break; }
    if (idx > 255u) return;                                                 /* every palette index is in use: leave the caption */
    H(b + CSS_TLUT + 2u * idx) = 0x8844u;                                   /* opaque dark blue (RGB5A3) */
    for (y = 43u; y < 54u; y++)
        for (x = 4u; x < 60u; x++) b[((y >> 2) * 8u + (x >> 3)) * 32u + (y & 3u) * 8u + (x & 7u)] = (u8)idx;
}

/* Stage icons (gnb_art.h GART_STAGE_N): MnSlMap.usd (NTSC 1.02, 636,811 B).  Its stage-select icons are CI8 images each followed by a 256-entry RGB565 palette: 64 x 56 with the
   palette at +0xE00 (the first 26 icons, 0x1020 apart from file offset 0xE2C0), 48 x 48 with it at +0x900 (the three Nintendo 64 stages).  One 4 KB block read from the file offset below,
   in the table order of gnb_art.h: 0x1F Battlefield, 0x20 Final Destination, 0x02 Fountain of Dreams, 0x08 Yoshi's Story, 0x03 Pokemon Stadium, 0x1C Dream Land. */
#define MAP_FILE_SIZE 636811u
static const u8 STG_ID[GART_STAGE_N] = { 0x1Fu, 0x20u, 0x02u, 0x08u, 0x03u, 0x1Cu };
static const u32 STG_OFF[GART_STAGE_N] = { 0x265C0u, 0x275E0u, 0x18400u, 0x163C0u, 0x1C480u, 0x28600u };
static const u8 STG_W[GART_STAGE_N] = { 64u, 64u, 64u, 64u, 64u, 48u };
static const u8 STG_H[GART_STAGE_N] = { 56u, 56u, 56u, 56u, 56u, 48u };
static const u16 STG_TLUT[GART_STAGE_N] = { 0xE00u, 0xE00u, 0xE00u, 0xE00u, 0xE00u, 0x900u };
static const u32 STG_SUM[GART_STAGE_N] = { 0x200D953Cu, 0xC4BE7106u, 0x31A265B8u, 0x4814B69Du, 0x401D3342u, 0xA5C6DF31u };
#define BK_N (GART_ICON_N + GART_STAGE_N)

/* block k (0 .. GART_ICON_N - 1 a fighter, then a stage): read, checked, its descriptor set built.  1 = ready */
static int blk_ok(unsigned k)
{
    u8 *b;
    u32 *j, d, m, t, off, sum, size, tlo, tlf;
    unsigned w, h;
    const char *file;
    int *ent;
    if (k >= BK_N) return 0;
    if (A.icon[k]) return 1;
    if (A.icon_bad[k]) return 0;
    if (k < GART_ICON_N) {
        if (!CSS_OFF[k]) return 0;
        file = "MnSlChr"; ent = &A.css_entry; size = CSS_FILE_SIZE; off = 0x20u + CSS_OFF[k]; sum = CSS_SUM[k]; w = GART_ICON_W; h = GART_ICON_H; tlo = CSS_TLUT; tlf = 2u;   /* RGB5A3 */
    } else {
        file = "MnSlMap"; ent = &A.map_entry; size = MAP_FILE_SIZE; off = STG_OFF[k - GART_ICON_N]; sum = STG_SUM[k - GART_ICON_N]; w = STG_W[k - GART_ICON_N]; h = STG_H[k - GART_ICON_N]; tlo = STG_TLUT[k - GART_ICON_N]; tlf = 1u;   /* RGB565 */
    }
    if (!A.open) { A.why = 1; return 0; }
    if (!(j = face_template())) { A.why = 2; return 0; }
    A.icon_bad[k] = 1;                                                      /* until proven good: one try per browser visit */
    if (!*ent) {
        char *full = FULLNAME(file);
        int e = full ? ENTRYNUM(full) : -1;
        *ent = (e > 0 && e < 0x4000 && FILE_SIZE(e) == size) ? e : -1;   /* a card-served (synthetic, >= 0x4000) or different file: no icons */
    }
    if (*ent < 0) { A.why = 3; return 0; }
    A.icon_heap = HSD_HEAP();
    b = (u8 *)OS_ALLOC(A.icon_heap, GART_ICON_BYTES);
    if (!b) { A.why = 4; return 0; }
    DC_INVAL(b, CSS_BLOCK);
    FILE_READ(*ent, off, (u32)b, CSS_BLOCK, 0x21, 1);
    DC_INVAL(b, CSS_BLOCK);
    if (fnv(b, CSS_BLOCK) != sum) { OS_FREE(A.icon_heap, b); A.why = 5; return 0; }
    /* the template's descriptors, copied, the texture pointed at the icon (the retail ones are never written) */
    d = dobj_n(j, 0); m = W(d + 8u); t = W(m + 8u);
    cpy(b + IB_JOINT, (const u8 *)j, 0x40u);
    W(b + IB_JOINT + 0x04u) &= ~JOBJ_HIDDEN;                                /* shown (the joint loads hidden in RAM: Dolphin run g5) */
    W(b + IB_JOINT + 0x08u) = 0; W(b + IB_JOINT + 0x0Cu) = 0; W(b + IB_JOINT + 0x10u) = (u32)(b + IB_DOBJ);
    cpy(b + IB_DOBJ, (const u8 *)d, 0x10u);
    W(b + IB_DOBJ + 0x04u) = 0; W(b + IB_DOBJ + 0x08u) = (u32)(b + IB_MOBJ);
    cpy(b + IB_MOBJ, (const u8 *)m, 0x18u);
    W(b + IB_MOBJ + 0x08u) = (u32)(b + IB_TOBJ);
    cpy(b + IB_TOBJ, (const u8 *)t, 0x5Cu);
    W(b + IB_TOBJ + 0x04u) = 0; W(b + IB_TOBJ + 0x4Cu) = (u32)(b + IB_IMG); W(b + IB_TOBJ + 0x50u) = (u32)(b + IB_TLUT);
    cpy(b + IB_IMG, (const u8 *)W(t + 0x4Cu), 0x18u);
    W(b + IB_IMG + 0x00u) = (u32)b; H(b + IB_IMG + 0x04u) = (u16)w; H(b + IB_IMG + 0x06u) = (u16)h; W(b + IB_IMG + 0x08u) = 9u; W(b + IB_IMG + 0x0Cu) = 0;
    cpy(b + IB_TLUT, (const u8 *)W(t + 0x50u), 0x10u);
    W(b + IB_TLUT + 0x00u) = (u32)(b + tlo); W(b + IB_TLUT + 0x04u) = tlf; H(b + IB_TLUT + 0x0Cu) = 256u;   /* GX_TL_RGB5A3 (fighters) / GX_TL_RGB565 (stages), 256 entries */
    if (k == 19u && !sheik_patch(b)) blank_caption(b);                   /* Sheik: its own icon from the build's delta over Zelda's block; else Zelda's with the patched "ZELDA" painted over so the cell can say SHEIK (GUI audit RM-02) */
    A.icon[k] = b;
    A.icon_bad[k] = 0;
    A.why = 8;
    return 1;
}

int gart_icon_ok(unsigned ch)
{
    if (ch >= GART_ICON_N) return 0;
    return blk_ok(ch);
}

/* block k on piece `slot` (the slot remembers the key.ch: a slot that changes its picture is made again) */
static int blk_put(unsigned slot, unsigned k, float x, float y, float z, float sx, float sy)
{
    u8 *j;
    if (slot >= GART_SLOTS) return 0;
    if (!blk_ok(k)) { gart_hide(slot); return 0; }
    if (A.p[slot].g && (A.p[slot].kind != GART_ICON || A.p[slot].ch != k)) free_slot(slot);
    if (!A.p[slot].g) {
        void *g = GOBJ_NEW(6, 7, 0x80), *jo;
        if (!g) return 0;
        jo = JOBJ_LOAD(A.icon[k] + IB_JOINT);
        if (!jo) { GOBJ_FREE(g); return 0; }
        GOBJ_OBJ(g, B(JOBJ_KIND), jo);
        GOBJ_LINK(g, (void *)JOBJ_DRAW, 4, 0x80);
        A.p[slot].g = g; A.p[slot].j = jo; A.p[slot].kind = GART_ICON; A.p[slot].ch = (u8)k;
    }
    j = (u8 *)A.p[slot].j;
    W((u32)A.p[slot].g + 0x1Cu) = JOBJ_DRAW;
    F(j + 0x38u) = x; F(j + 0x3Cu) = y; F(j + 0x40u) = z;
    F(j + 0x2Cu) = sx; F(j + 0x30u) = sy;
    dirty(j);
    return 1;
}

int gart_icon(unsigned slot, unsigned ch, float x, float y, float z, float sx, float sy)
{
    if (ch >= GART_ICON_N) { if (slot < GART_SLOTS) gart_hide(slot); return 0; }
    return blk_put(slot, ch, x, y, z, sx, sy);
}

static int stg_idx(unsigned sid) { unsigned i; for (i = 0; i < GART_STAGE_N; i++) if (STG_ID[i] == sid) return (int)i; return -1; }
int gart_stage_ok(unsigned sid) { int i = stg_idx(sid); return i >= 0 && blk_ok(GART_ICON_N + (unsigned)i); }
int gart_stage(unsigned slot, unsigned sid, float x, float y, float z, float sx, float sy)
{
    int i = stg_idx(sid);
    if (i < 0) { if (slot < GART_SLOTS) gart_hide(slot); return 0; }
    return blk_put(slot, GART_ICON_N + (unsigned)i, x, y, z, sx, sy);
}
unsigned gart_stage_w(unsigned sid) { int i = stg_idx(sid); return i < 0 ? 0u : STG_W[i]; }
unsigned gart_stage_h(unsigned sid) { int i = stg_idx(sid); return i < 0 ? 0u : STG_H[i]; }

unsigned gart_icon_why(void) { return A.why | ((unsigned)A.fstep << 4); }
unsigned gart_icon_heap(void)
{
    unsigned i, n = 0;
    for (i = 0; i < BK_N; i++) if (A.icon[i]) n += GART_ICON_BYTES;
    return n;
}

void gart_close(void)
{
    unsigned i;
    if (!A.open) return;
    for (i = 0; i < GART_SLOTS; i++) free_slot(i);
    (void)gart_bg(0);
    for (i = 0; i < BK_N; i++) { if (A.icon[i]) OS_FREE(A.icon_heap, A.icon[i]); A.icon[i] = 0; }   /* after the gobjs that drew them */
    if (A.traw) { OS_FREE(A.icon_heap, A.traw); A.traw = 0; }
    A.face = 0; A.face_tried = 0; A.css_entry = 0; A.map_entry = 0;
    gart_menu_panel(1);
    if (A.fig) ARC_FREE(A.fig);
    if (A.tou) ARC_FREE(A.tou);
    A.fig = 0; A.tou = 0; A.have = 0; A.open = 0;
}
