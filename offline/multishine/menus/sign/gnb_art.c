static void dirty(u8 *j)
{
    u32 fl = W(j + 0x14);
    if (!(fl & JOBJ_MTX_INDEP_SRT) && !(!(fl & JOBJ_USER_DEF_MTX) && (fl & JOBJ_MTX_DIRTY))) DIRTYSUB(j);
}

/* a box joint's corner bones (its children) carry its size: +-hw, +-hh by the sign each was made with */
static void bones(u8 *j, float hw, float hh)
{
    u8 *c = (u8 *)W(j + 0x10u);
    unsigned guard = 0;
    union { float f; u32 u; } X, Y;
    while (c && ok_ptr((u32)c) && guard++ < 8u) {
        X.f = hw; Y.f = hh;
        if (W(c + 0x38u) & 0x80000000u) X.u |= 0x80000000u;
        if (W(c + 0x3Cu) & 0x80000000u) Y.u |= 0x80000000u;
        F(c + 0x38u) = X.f; F(c + 0x3Cu) = Y.f;
        dirty(c);
        c = (u8 *)W(c + 0x08u);
    }
}

static void tint(u8 *j, unsigned rgb, float alpha, int all)
{
    u32 d = W(j + 0x18u);                                                   /* HSD_JObj.u.dobj; HSD_DObj: +4 next, +8 mobj, +0x14 flags; HSD_MObj +0xC mat: +4 diffuse, +0xC alpha */
    unsigned guard = 0;
    while (d && ok_ptr(d) && guard++ < 8u) {
        u32 m = W(d + 8u), mat = m && ok_ptr(m) ? W(m + 0xCu) : 0;
        if (mat && ok_ptr(mat)) {
            if (rgb) W(mat + 4u) = (rgb & 0xFFFFFF00u) | 0xFFu;
            F(mat + 0xCu) = alpha;
        }
        if (!all) break;
        d = W(d + 4u);
    }
}

/* every material of a loaded tree drawn in its own colour, unlit (RENDER_CONSTANT instead of RENDER_DIFFUSE / VERTEX): the Trophy Gallery is lit by its own scene's lights,
   the main menu's would turn its green to teal.  Before the first draw (the TEV is compiled then). */
static void unlit(u8 *j, unsigned depth)
{
    unsigned guard = 0;
    while (j && ok_ptr((u32)j) && guard++ < 64u && depth < 8u) {
        u32 d = W(j + 0x18u), g2 = 0;
        if (!(W(j + 0x14u) & 0x4020u))                                      /* not a spline / particle joint (JOBJ_SPLINE, JOBJ_PTCL): u is a DObj */
            while (d && ok_ptr(d) && g2++ < 8u) { u32 m = W(d + 8u); if (m && ok_ptr(m)) W(m + 4u) = (W(m + 4u) & ~6u) | 1u; d = W(d + 4u); }
        if (W(j + 0x10u)) unlit((u8 *)W(j + 0x10u), depth + 1u);
        j = (u8 *)W(j + 0x08u);
    }
}

static void dobj_hide(u8 *j, unsigned n)
{
    u32 d = W(j + 0x18u);
    while (d && n--) d = W(d + 4u);
    if (d && ok_ptr(d)) W(d + 0x14u) |= 1u;                                 /* DOBJ_HIDDEN */
}

static void free_slot(unsigned s)
{
    if (A.p[s].g) GOBJ_FREE(A.p[s].g);
    A.p[s].g = 0; A.p[s].j = 0; A.p[s].kind = 0; A.p[s].shape = 0;
}

static void *make(unsigned kind)
{
    void *desc = kind == GART_BADGE ? (void *)A.bj[0] : kind == GART_BOX ? (void *)A.box_d : kind == GART_BUTTON ? (void *)A.btn_d : kind == GART_FRAME ? (void *)A.fig_j : (void *)A.cur_j;
    void *g, *j;
    if (kind == GART_ICON || !(A.have & (1u << kind))) return 0;
    g = GOBJ_NEW(6, 7, 0x80);
    if (!g) return 0;
    j = JOBJ_LOAD(desc);
    if (!j) { GOBJ_FREE(g); return 0; }
    GOBJ_OBJ(g, B(JOBJ_KIND), j);
    GOBJ_LINK(g, (void *)JOBJ_DRAW, 4, 0x80);
    if (kind == GART_BUTTON) dobj_hide((u8 *)j, 1);                         /* the sort label ("Normal"): our text goes on the plate */
    if (kind == GART_FRAME) {
        void *x = 0;
        unlit((u8 *)j, 0);
        unsigned k;
        for (k = 0; k < sizeof FIG_HIDE; k++) { x = 0; (void)LB_JOBJ(j, &x, (int)FIG_HIDE[k], -1); if (x) JOBJ_SETALL(x, JOBJ_HIDDEN); }
        x = 0; (void)LB_JOBJ(j, &x, 2, -1); if (x) JOBJ_SETALL(x, JOBJ_HIDDEN);   /* the empty box in the lower right (the trophy description area, with its four corner bones) */
        if (!A.labels) { x = 0; (void)LB_JOBJ(j, &x, (int)FIG_HEAD, -1); if (x) { dobj_hide((u8 *)x, 1); dobj_hide((u8 *)x, 2); } x = 0; (void)LB_JOBJ(j, &x, (int)FIG_SIDE, -1); if (x) dobj_hide((u8 *)x, 0); }
    }
    return g;
}

void gart_put(unsigned slot, unsigned kind, float x, float y, float z, float hw, float hh, unsigned rgb, float alpha)
{
    u8 *j;
    if (slot >= GART_SLOTS || kind >= GART_KINDS) return;
    if (A.p[slot].g && A.p[slot].kind != kind) free_slot(slot);
    if (!A.p[slot].g) {
        void *g = make(kind);
        if (!g) return;
        A.p[slot].g = g; A.p[slot].j = (void *)W((u32)g + 0x28u); A.p[slot].kind = (u8)kind;
    }
    j = (u8 *)A.p[slot].j;
    W((u32)A.p[slot].g + 0x1Cu) = JOBJ_DRAW;                               /* shown (gart_hide swaps the gobj's render callback, the tree's own flags stay) */
    F(j + 0x38u) = x; F(j + 0x3Cu) = y; F(j + 0x40u) = z;
    if (kind == GART_BOX) {
        bones(j, hw, hh);
        F(j + 0x2Cu) = 1.0f; F(j + 0x30u) = 1.0f;                           /* gart_scale may shrink it after */
    } else { F(j + 0x2Cu) = hw; F(j + 0x30u) = hh; }
    dirty(j);
    tint(j, rgb, alpha, kind == GART_BUTTON);
}

/* ---- Grandmaster standings badges and rank icons ---- */
static void cp(u32 *d, u32 a, unsigned n) { unsigned i; for (i = 0; i < n; i++) d[i] = W(a + 4u * i); }
static void bcopy(u8 *d, const u8 *sr, unsigned n) { unsigned i; for (i = 0; i < n; i++) d[i] = sr[i]; }
int gart_badges_open(void)
{
    unsigned v, x, y;
    u32 dob, mob, tob;
    if (!gart_open() || !(A.have & (1u << GART_BUTTON)) || !A.btn_j) return 0;
    if (A.bdg) return 1;
    dob = W((u32)A.btn_j + 0x10u);
    if (!dob || !ok_ptr(dob) || !(mob = W(dob + 8u)) || !ok_ptr(mob) || !(tob = W(mob + 8u)) || !ok_ptr(tob) || !image_of(dob, 96u, 32u, 2u)) return 0;
#ifdef GNB_SETUP_ART
    if (!A.traw) {                                                          /* the GameSetup pictures' buffer, unpacked here once (a bad picture: none of them, the callers draw text) */
        A.icon_heap = HSD_HEAP();
        A.traw = (u8 *)OS_ALLOC(A.icon_heap, GTEX_TOTAL + 32u);
        if (A.traw) {
            unsigned g;
            for (g = 0; g < GT_N; g++) if (!gt_unpack(btex(BV_GT + g), (u32)GT_OFF[g + 1u] - GT_OFF[g], GT_PK[g], GT_PKN[g])) { OS_FREE(A.icon_heap, A.traw); A.traw = 0; break; }
        }
    }
#endif
    for (v = 0; v < GART_NVAR; v++) {
        u8 *t;
        unsigned w = STB_RI_L_W, h, fmt, bytes;
        if (v >= BV_BIG && v < BV_GT) continue;                             /* the retired 64 x 64 variants */
        if (v >= BV_GT) {
#ifdef GNB_SETUP_ART
            if (!A.traw) continue;
            w = GT_W[v - BV_GT]; h = GT_H[v - BV_GT]; t = btex(v); fmt = 2u; bytes = w * h;
            goto build;
#else
            continue;
#endif
        }
        t = btex(v); h = STB_RI_L_H;
        if (v < BV_COV) { bcopy(t, STB_RI_L[v], STB_RI_L_BYTES); fmt = 5u; bytes = STB_RI_L_BYTES; }                  /* RGB5A3 64 x 32, badge in the right half: already in tile order, rows bottom-up */
        else {
            w = STB_TEX_SIZE; h = STB_TEX_SIZE;
            for (y = 0; y < STB_TEX_SIZE; y++)                              /* row-major 4-bit coverage -> IA4 8 x 4 tiles */
                for (x = 0; x < STB_TEX_SIZE; x++) {
                    unsigned px = (STB_TEX_SIZE - 1u - y) * STB_TEX_SIZE + x, a = (STB_TEX[v - BV_COV][px >> 1] >> ((px & 1u) ? 0 : 4)) & 15u;
                    t[((y >> 2) * (STB_TEX_SIZE >> 3) + (x >> 3)) * 32u + (y & 3u) * 8u + (x & 7u)] = (u8)((a << 4) | 15u);
                }
            fmt = 2u; bytes = STB_TEX_SIZE * STB_TEX_SIZE;
        }
    build:
        DC_STORE(t, bytes);
        copy_desc(A.bj[v], A.btn_j);
        cp(A.bdo[v], dob, 4); A.bdo[v][1] = 0;                              /* the plate's quad and material only: no label dobj */
        cp(A.bmo[v], mob, 8);
        cp(A.bto[v], tob, 24); A.bto[v][1] = 0;
        cp(A.bim[v], W(tob + 0x4Cu), 8);
        A.bim[v][0] = (u32)t; A.bim[v][1] = (w << 16) | h; A.bim[v][2] = fmt;
        A.bto[v][15] = 0x01010000u | (A.bto[v][15] & 0xFFFFu);              /* repeat_s / repeat_t 1: the plate's texture is mirrored twice down its height (repeat_t 2), ours is one badge */
        A.bto[v][19] = (u32)A.bim[v];
        A.bmo[v][2] = (u32)A.bto[v];
        A.bdo[v][2] = (u32)A.bmo[v];
        A.bj[v][4] = (u32)A.bdo[v];
    }
    A.bdg = 1;
    return 1;
}

/* one piece of variant v in a slot at (x, y, z), scale (sx, sy), material tint rgb (0xRRGGBB00; the rank icons are drawn untinted: white) */
static void badge_put(unsigned slot, unsigned v, float x, float y, float z, float sx, float sy, unsigned rgb, float alpha)
{
    u8 *j;
    if (slot >= GART_SLOTS || v >= GART_NVAR || !A.bdg) return;
    if (A.p[slot].g && (A.p[slot].kind != GART_BADGE || A.p[slot].shape != v)) free_slot(slot);
    if (!A.p[slot].g) {
        void *g = GOBJ_NEW(6, 7, 0x80), *o;
        if (!g) return;
        o = JOBJ_LOAD((void *)A.bj[v]);
        if (!o) { GOBJ_FREE(g); return; }
        GOBJ_OBJ(g, B(JOBJ_KIND), o);
        GOBJ_LINK(g, (void *)JOBJ_DRAW, 4, 0x80);
        A.p[slot].g = g; A.p[slot].j = (void *)W((u32)g + 0x28u); A.p[slot].kind = GART_BADGE; A.p[slot].shape = (u8)v;
    }
    j = (u8 *)A.p[slot].j;
    W((u32)A.p[slot].g + 0x1Cu) = JOBJ_DRAW;
    F(j + 0x38u) = x; F(j + 0x3Cu) = y; F(j + 0x40u) = z;
    F(j + 0x2Cu) = sx; F(j + 0x30u) = sy;
    dirty(j);
    tint(j, rgb, alpha, 1);
}

