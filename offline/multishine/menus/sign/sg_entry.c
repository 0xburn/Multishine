static void ln_scopy(char *d, const char *s, unsigned cap) { unsigned i = 0; while (s[i] && i + 1u < cap) { d[i] = s[i]; i++; } while (i < cap) d[i++] = 0; }
static int ln_save(unsigned now)
{
    struct od_cfg *cfg = g_id ? (struct od_cfg *)g_id->cfg : 0;
    mnc *c = g_ucfg.net;
    unsigned i;
    int r;
    if (!cfg || !c) return -1;
    if (!LN.inforce) {                                                 /* the identity goes into force once (RAM): the config, then the hub client */
        LN.inforce = 1;
        for (i = 0; i < 8u; i++) cfg->dev[i] = LK.dev[i];
        for (i = 0; i < 16u; i++) cfg->tok[i] = LK.secret[i];
        ln_scopy(cfg->code, LK.code, sizeof cfg->code); ln_scopy(cfg->name, LK.name, sizeof cfg->name);
        for (i = 0; i < 8u; i++) c->dev[i] = LK.dev[i];
        for (i = 0; i < 16u; i++) c->tok[i] = LK.secret[i];
        ln_scopy(c->code, LK.code, MNC_STR); ln_scopy(c->name, LK.name, MNC_STR);
        c->have_id = 1;
        mw2_drop(&c->w);                                               /* the old (anonymous or guest) session ends; the next request handshakes with the new secret */
        for (i = 0; i < 16u; i++) LK.secret[i] = 0;                    /* the only copies now: the resident config and the hub client */
        G.linked = SG_ID_RAMONLY;
    }
    r = g_id->save ? g_id->save(cfg) : -1;
    LN.save_tries++;
    if (r == 1 && LN.save_tries < 4u) { LN.save_at = now + 2000u; return 1; }   /* the card is busy (Melee's own card layer): again in 2 s, 3 tries */
    LN.save_tries = 0;
    if (r == 0) G.linked = SG_ID_LINKED;
    id_refresh();
    return r == 1 ? -2 : r;
}
/* the stored entropy seed of MultishineOptions: read once when the entropy pass would show (a card that has one skips the pass: up to 128
   credited bits, once), and replaced by a fresh one (domain-separated output of the pool, sdent_export_seed) once the link has used the pool, so a stored seed is never
   credited twice */
static void lk_seed(struct sgl *k)
{
    unsigned char rec[SDENT_SEED_REC_LEN], seed[32];
    sdc_u32 bits = 0;
    unsigned i;
    if (!g_id || !g_id->seed) return;
    if (k->st == SGL_ENT && !LN.seed_tried) {
        int r = g_id->seed(rec, 0);
        if (r < 0) return;                                             /* the options record is not read yet: next frame */
        LN.seed_tried = 1;
        if (r == 1 && sdent_seed_parse(rec, sizeof rec, seed, &bits) == 0) sdent_load_seed(&k->pool, SDENT_STORED, seed, bits);
    } else if ((k->st == SGL_SHOW || k->st == SGL_DONE) && !LN.seed_saved) {
        LN.seed_saved = 1;
        if (sdent_export_seed(&k->pool, seed, &bits) == 0) {
            sdent_seed_pack(seed, bits, rec);
            (void)g_id->seed(rec, 1);
        }
    } else return;
    for (i = 0; i < sizeof seed; i++) seed[i] = 0;
    for (i = 0; i < sizeof rec; i++) rec[i] = 0;
}
/* the first run's Slippi offer (sg_link.c SGL_SLCHK): only when the card has no Slippi login and the offer was not shown on an earlier first run.  "Shown before" is a
   marker in the stored-seed slot of MultishineOptions (no new card file): the record "SDSL" 1, which sdent_seed_parse rejects like an empty slot, so the link's entropy pass is not
   affected; it is written only over an empty slot or a non-seed record, never over a real stored seed (a real seed means the link ran: the console is linked or will be asked again anyway) */
static void dl_probe(void);
static void lk_slippi_check(struct sgl *k)
{
    unsigned char rec[SDENT_SEED_REC_LEN], seed[32];
    sdc_u32 bits = 0;
    int r = 0, show = 1;
    unsigned i;
    if (!G.id_slippi) dl_probe();
    if (g_id && g_id->seed) r = g_id->seed(rec, 0);
    if ((!G.id_slippi || r < 0) && LN.sl_tries < 180u) { LN.sl_tries++; return; }           /* the card or the options record is not read yet: next frame (3 s at most) */
    k->req = SGL_R_NONE;
    if (G.id_slippi == 2u) show = 0;                                       /* a Slippi login is on the card already */
    else if (r == 1 && rec[0] == 'S' && rec[1] == 'D' && rec[2] == 'S' && rec[3] == 'L') show = 0;      /* offered on an earlier first run */
    else if (r >= 0 && g_id && g_id->seed && !(r == 1 && sdent_seed_parse(rec, sizeof rec, seed, &bits) == 0)) {
        for (i = 0; i < sizeof rec; i++) rec[i] = 0;
        rec[0] = 'S'; rec[1] = 'D'; rec[2] = 'S'; rec[3] = 'L'; rec[4] = 1;
        (void)g_id->seed(rec, 1);
    }
    for (i = 0; i < sizeof seed; i++) seed[i] = 0;
    for (i = 0; i < sizeof rec; i++) rec[i] = 0;
    LN.sl_tries = 0;
    sgl_slchecked(&G, show);
}
static void lk_net(void)
{
    struct sgl *k = &G.lk;
    mnc *c = g_ucfg.net;
    unsigned now = env->now_ms ? env->now_ms() : 0u;
    k->now = now;
    if (G.scr == SG_LINK) lk_seed(k);
    if (LN.phase == 1) {
        int st = lnk_poll(&LK, now);
        if (st == LNK_BUSY) return;
        LN.phase = 0;
        if (st == LNK_DONE && LN.op == LNK_OP_START) sgl_started(k, LK.user, LK.expires, LK.interval);
        else if (st == LNK_DONE) sgl_linked(k, LK.code, LK.name);
        else sgl_failed(k, LK.err == LNK_E_SERVER || LK.err == LNK_E_HS ? 0u : (LK.err == LNK_E_BAD_REPLY ? SGL_E_BAD : SGL_E_UNREACH), (unsigned)LK.status);
        return;
    }
    if (LN.phase == 2) {                                               /* the HELLO in a device session with the new identity */
        (void)g_ucfg.poll(now);
        if (c->state == MNC_DONE) { LN.phase = 0; G.id_sync = 1; sgl_verified(k, 1); }
        else if (c->state == MNC_FAILED) { LN.phase = 0; sgl_verified(k, 0); }
        return;
    }
    if (LN.save_at && k->req == SGL_R_NONE && k->st == SGL_SAVE) {     /* a busy card: the retry */
        if ((int)(now - LN.save_at) < 0) return;
        LN.save_at = 0;
        k->req = SGL_R_SAVE;
    }
    switch (k->req) {
    case SGL_R_NONE: return;
    case SGL_R_SLCHK: lk_slippi_check(k); return;
    case SGL_R_CANCEL:
        k->req = SGL_R_NONE;
        if (LK.c) lnk_cancel(&LK, now);
        ln_wipe();
        return;
    case SGL_R_START: {
        unsigned char seed[16], key[32];
        unsigned i;
        k->req = SGL_R_NONE;
        if (!c || !g_ucfg.link_up || !g_ucfg.link_up()) { sgl_failed(k, SGL_E_OFFLINE, 0); return; }
        if (sdent_bytes(&k->pool, SDENT_L_SESSION, seed, sizeof seed) != 0 || sdent_bytes(&k->pool, SDENT_L_SESSION, key, sizeof key) != 0) { sgl_failed(k, SGL_E_BAD, 0); return; }
        ln_wipe();
        lnk_init(&LK, c, seed, sizeof seed);
        lnk_set_key(&LK, key);
        for (i = 0; i < 32u; i++) key[i] = 0;
        for (i = 0; i < 16u; i++) seed[i] = 0;
        LN.op = LNK_OP_START;
        if (lnk_start(&LK, now) != 0) { sgl_failed(k, SGL_E_UNREACH, 0); return; }
        LN.phase = 1;
        return;
    }
    case SGL_R_POLL:
        k->req = SGL_R_NONE;
        LN.op = LNK_OP_POLL;
        if (lnk_poll_req(&LK, now) != 0) { sgl_failed(k, SGL_E_UNREACH, 0); return; }
        LN.phase = 1;
        return;
    case SGL_R_SAVE: {
        int r;
        k->req = SGL_R_NONE;
        r = ln_save(now);
        if (r == 1) return;                                            /* busy: retried */
        if (r == 0) { unsigned i; for (i = 0; i < sizeof LK; i++) ((unsigned char *)&LK)[i] = 0; }
        sgl_saved(k, r);
        return;
    }
    case SGL_R_VERIFY:
        k->req = SGL_R_NONE;
        if (!c || !g_ucfg.hello || c->state == MNC_BUSY || g_ucfg.hello(now) != 0) { sgl_verified(k, 0); return; }
        LN.phase = 2;
        return;
    default:
        k->req = SGL_R_NONE;
        return;
    }
}
/* ---- Device Identity and Delete This Console's Identity (/ 3.2, sg_delid.c).  The card is looked at once per overlay session
   (does MultishineIdentity exist: never its contents); the delete runs server first (DEVICE_FORGET 0x1A in the hub client's device session, HELLO first when needed),
   then the card record (the resident writer with the guest placeholder identity: all-zero device id and secret, code GUEST@0), then the Slippi login files if chosen,
   then RAM (the hub client forgets the identity and its session keys). ---- */
#include "../upd/upd_card.h"
#define DL_GUEST_CODE "GUEST@0"            /* the placeholder of a guest record (menus/hub/run_seat_card.sh --guest, onfile.py); the console never sends it */
#define DL_GUEST_NAME "Guest"
static struct { unsigned char phase, tries, probed; unsigned at; } DL;   /* phase 0 idle, 1 HELLO running, 2 DEVICE_FORGET running */
static void dl_probe(void)
{
    const struct ota_card_ops *o;
    int r;
    if (DL.probed || G.id_slippi || !upc_ready()) return;
    DL.probed = 1;
    o = upc_ops();
    r = o->exists(o->ctx, "MultishineIdentity");
    if (r != 1 && sgr_recover(&SRH) == 1) r = 1;                       /* a Send Slippi Login swap that stopped half way: the old record is put back (sgr.c) */
    upc_done();
    G.id_slippi = (unsigned char)(r == 1 ? 2u : 1u);
}
/* The Slippi part of the delete sequence (level 2 and 3), and the same clear the website's "Remove Slippi login" asks for (sgc.c): MultishineIdentity, its staging and previous
   records of an interrupted swap (sgr.c, so no recovery can bring the login back) and MultishineBridge (the status cache that belongs to that identity).  A file that is not there
   counts as gone.  Never the device key, never the Multishine link (MultishineOnline), never Melee's save.  0 = all gone, else failed (the card was busy or missing). */
static int dl_clear_one(const struct ota_card_ops *o, const char *name)
{
    int e = o->exists(o->ctx, name);
    return e == 0 ? 0 : o->del(o->ctx, name);
}
static int dl_slippi_clear(void)
{
    const struct ota_card_ops *o;
    int a, b, c, d;
    if (!upc_ready()) return -1;
    o = upc_ops();
    a = dl_clear_one(o, SGR_ID_NAME);
    c = dl_clear_one(o, SGR_ID_NEW);
    d = dl_clear_one(o, SGR_ID_OLD);
    b = dl_clear_one(o, "MultishineBridge");
    upc_done();
    if (a == 0) G.id_slippi = 1;
    return (a == 0 && b == 0 && c == 0 && d == 0) ? 0 : -1;
}
static void dl_forgot(int ok)
{
    unsigned i;
    mnc *c = g_ucfg.net;
    DL.phase = 0;
    for (i = 0; i < sizeof LK; i++) ((unsigned char *)&LK)[i] = 0;
    sgd_server(&G.del, ok);
    (void)c;
}
static void dl_net(void)
{
    struct sgd *d = &G.del;
    mnc *c = g_ucfg.net;
    unsigned now = env->now_ms ? env->now_ms() : 0u;
    if (G.scr == SG_HUB || G.scr == SG_IDENT || G.scr == SG_DELID) dl_probe();
    if (DL.phase == 1) {                                               /* the HELLO that opens the device session */
        (void)g_ucfg.poll(now);
        if (c->state == MNC_FAILED) { dl_forgot(c->status == 4 || c->status == 26); return; }   /* AUTH_FAILED / TOKEN_REVOKED: the server does not know this device */
        if (c->state != MNC_DONE) return;
        lnk_init(&LK, c, 0, 0);
        if (lnk_forget(&LK, now, 0) != 0) { dl_forgot(0); return; }
        DL.phase = 2;
        return;
    }
    if (DL.phase == 2) {
        int st = lnk_poll(&LK, now);
        if (st == LNK_BUSY) return;
        dl_forgot(st == LNK_DONE || (LK.err == LNK_E_SERVER && (LK.status == 4 || LK.status == 26)));
        return;
    }
    switch (d->req) {
    case SGD_R_FORGET:
        d->req = SGD_R_NONE;
        if (!c || !g_ucfg.link_up || !g_ucfg.link_up() || !g_ucfg.hello || !g_ucfg.poll || c->state == MNC_BUSY) { sgd_server(d, 0); return; }
        if (c->have_hello && c->w.dev_sess && mw2_ready(&c->w, now)) {
            lnk_init(&LK, c, 0, 0);
            if (lnk_forget(&LK, now, 0) != 0) { sgd_server(d, 0); return; }
            DL.phase = 2;
            return;
        }
        if (g_ucfg.hello(now) != 0) { sgd_server(d, 0); return; }
        DL.phase = 1;
        return;
    case SGD_R_CARD: {
        struct od_cfg *cfg = g_id ? (struct od_cfg *)g_id->cfg : 0;
        unsigned i;
        int r = -1;
        if (DL.at && (int)(now - DL.at) < 0) return;                   /* a busy card: the retry in 2 s */
        DL.at = 0;
        if (cfg) {
            for (i = 0; i < 8u; i++) cfg->dev[i] = 0;
            for (i = 0; i < 16u; i++) cfg->tok[i] = 0;
            ln_scopy(cfg->code, DL_GUEST_CODE, sizeof cfg->code); ln_scopy(cfg->name, DL_GUEST_NAME, sizeof cfg->name);
            r = g_id->save ? g_id->save(cfg) : -1;
            if (r == 1 && ++DL.tries < 4u) { DL.at = now + 2000u; if (!DL.at) DL.at = 1; return; }
        }
        DL.tries = 0;
        d->req = SGD_R_NONE;
        if (c) {                                                       /* RAM: the hub client forgets the identity and its session keys; the next search mints a guest token */
            for (i = 0; i < 8u; i++) c->dev[i] = 0;
            for (i = 0; i < 16u; i++) c->tok[i] = 0;
            c->code[0] = 0; c->name[0] = 0; c->have_id = 0;
            mw2_drop(&c->w);
            mw2_use(&c->w, 0, 0);
        }
        G.linked = SG_ID_GUEST; G.id_sync = 0;
        id_refresh();
        sgd_card(d, r == 0);
        return;
    }
    case SGD_R_KEY: {                                                  /* level 3: the stored entropy seed (the console key) is replaced by an all-zero record, which parses as 'no seed'; saved by the settings layer */
        unsigned char rec[SDENT_SEED_REC_LEN];
        unsigned i;
        int r = -1;
        for (i = 0; i < sizeof rec; i++) rec[i] = 0;
        if (g_id && g_id->seed) r = g_id->seed(rec, 1);
        sdent_init(&G.lk.pool); LN.seed_tried = 0; LN.seed_saved = 0;      /* the link's RAM pool forgets what an earlier link in this session credited: the next link asks for entropy again */
        d->req = SGD_R_NONE;
        sgd_key(d, r == 1);
        return;
    }
    case SGD_R_SLIPPI:
        d->req = SGD_R_NONE;
        sgd_slippi(d, dl_slippi_clear() == 0);
        return;
    default:
        return;
    }
}
