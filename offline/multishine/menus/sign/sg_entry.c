static void st_net(void)
{
    struct stb *b = &G.sd;
    mnc *c = g_ucfg.net;
    unsigned now = env->now_ms ? env->now_ms() : 0u;
    if (G.scr != SG_STAND) { if (SN.phase == 2) gnc_abort(&GC); SN.phase = 0; return; }
    if (SN.phase == 0) {
        if (b->req == STB_REQ_NONE) return;
        b->req = STB_REQ_NONE;
        if (!c || !g_ucfg.link_up || !g_ucfg.link_up() || !g_ucfg.hello || !g_ucfg.poll) { st_fail(STB_W_UNREACH); return; }
        if (c->state == MNC_BUSY) { st_fail(STB_W_UNREACH); return; }
        if (!c->have_hello || !mw2_ready(&c->w, now)) {
            if (g_ucfg.hello(now) != 0) { st_fail(STB_W_UNREACH); return; }
            SN.phase = 1;
            return;
        }
        st_issue(now);
        return;
    }
    if (SN.phase == 1) {
        (void)g_ucfg.poll(now);
        if (c->state == MNC_DONE) st_issue(now);
        else if (c->state == MNC_FAILED) st_fail(STB_W_UNREACH);
        return;
    }
    {
        int st = gnc_poll(&GC, now);
        if (st == GNC_DONE) st_done();
        else if (st == GNC_FAILED) {
            if (GC.err == GNC_E_NOSESSION && !SN.rehello && g_ucfg.hello(now) == 0) { SN.rehello = 1; SN.phase = 1; return; }      /* the server forgot the session: one fresh handshake */
            st_fail(st_why(GC.err, GC.status));
        }
    }
}
