static int same_str(const char *a, const char *b)
{
    while (*a && *a == *b) { a++; b++; }
    return *a == *b;
}
static void copy_str(char *d, const char *s) { while ((*d++ = *s++) != 0) { } }

/* O-8: the collecting screens (make the console key, entropy test while it runs) change their counters every frame; every changed row is a
   new Melee text object (allocate + free), so they are redrawn at most SG_COLLECT_RATE_FRAMES apart (3 per second), the first draw of a screen at once. */
#define SG_COLLECT_RATE_FRAMES 20u
static unsigned p_frames, p_last_draw, p_last_scr = 0xFFu;
