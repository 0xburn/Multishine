static gnc GC;
/* what the last room list said about the server (GC is zeroed by every gnc_init): the list version it answered (6 room types, 5, 4), the admin switches it carries.  Room types are served when the list was a v6 reply (list flag
   bit 2, the console's one reliable signal; the HELLO caps2 byte says the same); against an older server every screen behaves as before and the match report carries no character bytes (GNS_RF_CHARS). */
