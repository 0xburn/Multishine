    unsigned i;
    V[0] = t->var; V[1] = PR.phase; V[2] = PR.err_phase; V[3] = (sgo_u32)(PR.r_err < 0 ? -PR.r_err : PR.r_err); V[4] = (sgo_u32)(PR.r_tcp_err < 0 ? -PR.r_tcp_err : PR.r_tcp_err);
    V[5] = (sgo_u32)(PR.r_tls_err < 0 ? -PR.r_tls_err : PR.r_tls_err); V[6] = PR.r_tcp_connect_ms; V[7] = PR.r_echo_ok; V[8] = PR.r_down_bytes; V[9] = PR.r_down_ms; V[10] = PR.r_down_bad;
    V[11] = PR.r_tls_tcp_ms; V[12] = PR.r_tls_hs_ms; V[13] = PR.r_x25519_us[0]; V[14] = PR.r_x25519_us[1]; V[15] = PR.r_verify_us; V[16] = PR.r_heavy_max_us; V[17] = PR.r_heavy_total_us;
    V[18] = PR.r_hello_ok; V[19] = PR.r_https_bytes; V[20] = PR.r_https_ms; V[21] = PR.r_https_bad; V[22] = PR.r_https_status; V[23] = PR.r_tcp_retrans; V[24] = PR.r_tcp_rto; V[25] = PR.r_tcp_ooo;
