static void o_goto(sgo_u32 scr)
{
    unsigned offer = (scr & SG_GOTO_OFFER) != 0u;                  /* the first-run offer after START (hub_ovl.h fr_step, ml_glue.c) */
    unsigned dev = (scr & SG_GOTO_DEV) != 0u;                      /* Settings > Diagnostics > Server And Slippi: the Online page's lab rows alone */
    unsigned room = (scr & SG_GOTO_ROOM) != 0u ? (unsigned)(scr >> 16) : 0u;               /* a toast's room: code + 1 (1..10000) */
    unsigned page = (scr & SG_GOTO_PAGE) != 0u ? (unsigned)(scr >> 16) : 0u;               /* Settings > Account / Friends and privacy / Delete: that Online page alone */
    unsigned sysf = (scr & SG_GOTO_SYSF) != 0u;                    /* the automatic system-files set-up */
    unsigned prog = (scr & SG_GOTO_PROG) != 0u;                    /* the first run STARTS with the progressive scan question (its own screen) */
    unsigned progw = (scr & SG_GOTO_PROGW) != 0u;                  /* a Wii: the question turns the picture on for the next start */
    unsigned mine = (scr & SG_GOTO_MINE) != 0u;                    /* back from the animated bracket: the bracket of the player's cup, not the list */
    scr &= 0xFFu;
    sg_goto(&G, scr);
    if (mine && scr == SG_TOURN) gnt_enter_mine(&G.tn);
    if (room >= 1u && room <= 10000u && scr == SG_GN) {
        char rc[5];
        unsigned v = room - 1u;
        rc[0] = (char)('0' + v / 1000u % 10u); rc[1] = (char)('0' + v / 100u % 10u); rc[2] = (char)('0' + v / 10u % 10u); rc[3] = (char)('0' + v % 10u); rc[4] = 0;
        gnb_join_friend(&G.gn, rc, 0u);                                 /* the same join as Y on a friend's Room row: the browser asks for the passcode itself when the server says so */
    }
#if SG_NETSEL
    if (dev && scr == SG_HUB) { G.dev = 1; G.cur = SG_ON_SRV; }
#endif
    if (page && scr == SG_HUB) sg_hub_page(&G, page);
    G.direct = (unsigned char)(scr == SG_CTL || scr == SG_ENT || scr == SG_UPD || offer || dev || (prog && scr == SG_LINK));      /* a screen opened straight from the menu: Back leaves the overlay */
    G.prog_ask = (unsigned char)(scr == SG_LINK && prog); G.prog_try = 0; G.prog_wii = (unsigned char)(progw && G.prog_ask); G.sl_chain = 0;      /* (a kept overlay block is opened again: nothing of an earlier first run stays) */
    if (prog && scr == SG_LINK) sgl_progq(&G);                     /* the progressive scan question alone: the first step of the first run */
    else if (offer && scr == SG_LINK) sgl_offer(&G);
    G.sysf = (unsigned char)(sysf && scr == SG_UPD); G.sysf_t = 0;
    if (scr == SG_UPD && sysf) G.upd.req |= SGU_REQ_SYSFILES;      /* MultishinePack is missing: the glue opened this screen to set it up; no key is needed */
    else if (scr == SG_UPD) G.upd.req |= SGU_REQ_CHECK;                  /* the update check on the title found an update ( "Check on title"): the offer at once */
}
