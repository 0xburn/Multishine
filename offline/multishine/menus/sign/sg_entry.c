/* the Game Night browser: build the retail Event Match screen for screens SG_GN / SG_MK_GNG, feed it the model, leave through it.
   The character-cell text view of the model is never shown here: a refused or failed open is asked
   again (as Friends, fr_glue) while the loading cover stays; an Event screen that is still up when the model was entered again is taken over (it is the same struct);
   only when the screen cannot be built for about 2 s a short message is drawn instead (gn_min_view, B leaves) and the open is still retried behind it. */
static void gn_glue(void)
{
    int on = G.scr == SG_GN || G.scr == SG_MK_GNG, st = gnbev_state();
    if (!on) { gn_tries = 0; gn_wait = 0; gn_min = 0; }
    if (on && !G.gn.gfx && (st == GNBEV_UP || st == GNBEV_LAUNCH)) {      /* the model was entered again (gnb_enter zeroes gfx) while its Event screen stayed: take it over, never leave it frozen under the text view */
        present_free();
        G.gn.gfx = 1; G.gn.gfx_tried = 1; G.gn.dirty = GNB_D_ALL; gn_min = 0;
        return;
    }
    if (on && !G.gn.gfx && !G.gn.gfx_tried && st == GNBEV_IDLE) {
        if (gn_wait) { gn_wait--; return; }
        if (!gn_min) present_free();                          /* our backdrop and rows go: the Event screen is the picture */
        if (gnbev_open(&G.gn) == 0) {
            if (gn_min) present_free();                       /* the short message goes before the Event screen is built (next proc pass) */
            G.gn.gfx = 1; G.gn.gfx_tried = 1; gn_tries = 0; gn_min = 0;
        } else {
            gnbev_reset();                                    /* no menu think to take over (a momentary refusal, e.g. the menu is being rebuilt): ask again */
            if (gn_tries < 255u) gn_tries++;
            gn_wait = gn_tries < 6u ? 20u : 60u;              /* six tries every 20 frames, then once a second, without limit */
            if (gn_tries >= 6u) gn_min = 1;
        }
        return;
    }
    if (!G.gn.gfx) return;
    if (st == GNBEV_UP) { if (G.gn.exit) gnbev_close(); else gnbev_frame(); return; }
    if (st == GNBEV_CLOSED || st == GNBEV_FAILED) {
        int left = st == GNBEV_CLOSED;
        gnbev_reset();
        G.gn.gfx = 0;
        if (!left) {                                          /* failed while launching: asked again like a refused open (never the text view) */
            G.gn.gfx_tried = 0;
            if (gn_tries < 255u) gn_tries++;
            gn_wait = gn_tries < 6u ? 20u : 60u;
            if (gn_tries >= 6u) gn_min = 1;
            return;
        }
        if (G.gn.back_frd && (tn_back || G.gn.tn.on)) { unsigned had = tn_back; tn_back = 0; G.gn.back_frd = 0; G.gn.exit = 0; sg_goto(&G, SG_TOURN); if (had) gnt_resume(&G.tn, &tn_resume_ent); else gnt_enter_mine(&G.tn); }   /* (tn.on without tn_back: the room was resumed after a game, the overlay's RAM is new: the list finds the cup, gnt_enter_mine) */     /* a tournament match room was left: the bracket again */
        else if (G.gn.back_frd) { G.gn.back_frd = 0; G.gn.exit = 0; sg_goto(&G, SG_FRD); }      /* a room joined from the Friends list was left: the Friends list again (fr_glue builds its Event screen) */
        else if (G.scr == SG_MK_GNG) sg_goto(&G, SG_MOCK);
        else if (G.mk.on) sg_goto(&G, SG_MOCK);
        else G.quit = 1;
    }
}
