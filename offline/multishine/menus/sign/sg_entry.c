{
    return (G.scr == SG_MAKEKEY && !G.sub) || (G.scr == SG_ENT && G.ent.state == SG_ET_RUN) || (G.scr == SG_UPD && (G.upd.state == SGU_DOWNLOADING || (G.sysf && G.upd.state == SGU_INSTALLING)));   /* the progress row changes with every chunk */
}

