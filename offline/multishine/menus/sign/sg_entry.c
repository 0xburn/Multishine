static void tls_fill(void)
{
    struct sg_tls_view *t = &G.tls;
    char *p = t->server;
    sgo_u32 ip = lab_target();
    p = sg_u(p, ip >> 24); *p++ = '.'; p = sg_u(p, (ip >> 16) & 255u); *p++ = '.'; p = sg_u(p, (ip >> 8) & 255u); *p++ = '.'; p = sg_u(p, ip & 255u);
    *p++ = ':'; p = sg_u(p, lab_tls_port()); *p = 0;
    t->started = g_tls_state >= 2;
    t->want_down = lab_bulk();
    t->diag = (sdc_u8)g_dg_state;
    if (g_tls_state < 2) return;
    t->phase = PR.phase;
    t->done = PR.phase == SDPROBE_DONE;
    t->failed = PR.phase == SDPROBE_FAILED;
    t->err_phase = PR.err_phase;
    t->err = PR.r_err; t->tcp_err = PR.r_tcp_err; t->tls_err = PR.r_tls_err;
    t->tcp_connect_ms = PR.r_tcp_connect_ms; t->echo_ok = PR.r_echo_ok;
    t->down_bytes = PR.r_down_bytes; t->down_ms = PR.r_down_ms; t->down_bad = PR.r_down_bad;
    t->tls_tcp_ms = PR.r_tls_tcp_ms; t->tls_hs_ms = PR.r_tls_hs_ms;
    t->x25519_us0 = PR.r_x25519_us[0]; t->x25519_us1 = PR.r_x25519_us[1]; t->verify_us = PR.r_verify_us;
    t->heavy_total_us = PR.r_heavy_total_us; t->heavy_max_us = PR.r_heavy_max_us; t->hello_ok = PR.r_hello_ok;
    t->https_bytes = PR.r_https_bytes; t->https_ms = PR.r_https_ms; t->https_bad = PR.r_https_bad; t->https_status = PR.r_https_status;
    t->retrans = PR.r_tcp_retrans;
    t->dbg[0] = TCP.st.seg_rx; t->dbg[1] = TCP.st.rst_rx; t->dbg[2] = TCP.st.rst_tx; t->dbg[3] = TCP.st.no_conn; t->dbg[4] = TCP.st.bad_csum; t->dbg[5] = ((sgo_u32)CONN[0].lport << 16) | (CONN[0].iss & 0xFFFFu);
    if (!t->done && !t->failed) t->elapsed_ms = env->now_ms() - g_tls_t0;
}

