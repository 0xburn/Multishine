/* ---- a Grandmaster set: the same browser screen, the ranked set ops (RK_SET_STATE / RK_SET_ACTION / MATCH_STATUS) on the same session. The set's facts live in the
   resident hand-off block (mnc.h MNC_RK_*): this overlay is freed and loaded again between the games. ---- */
static struct { unsigned char on, lv, retry_what, sent; unsigned retry_at, lv_t; } RKS;       /* lv: forfeit sends that found the hub client busy (tried again, 6 times at most); retry_what: the request to send again at retry_at (0: the state) */
static int rk_hand_ok(const mnc *c);
static unsigned gn_why(unsigned what, int err, int status)
{
    if (err == GNC_E_SERVER) {
        switch (status) {
        case GNC_ST_UNKNOWN_OP: case GNC_ST_NOT_SUPPORTED: return GNB_W_NOGN;
        case GNC_ST_AUTH_FAILED: case GNC_ST_ACCOUNT_NEEDED: return GNB_W_SIGNIN;
        case GNC_ST_NOT_FOUND: return GNB_W_NOTFOUND;
        case GNC_ST_LIMIT_REACHED: return GNB_W_FULL;
        case GNC_ST_UPDATE_REQUIRED: return GNB_W_BUILD;
        case GNC_ST_CODESET_MISMATCH: case GNC_ST_RULES_MISMATCH: return GNB_W_RULES;
        case GNC_ST_RATE_LIMITED: return GNB_W_RATE;
        case GNC_ST_BAD_REQUEST: return (what == GNB_REQ_JOIN || what == GNB_REQ_CREATE) ? GNB_W_INROOM : GNB_W_BAD;
        default: return GNB_W_SERVER;
        }
    }
    return GNB_W_UNREACH;
}
static void rk_fail(unsigned why)
{
    struct gnb *b = &G.gn;
    unsigned now = env->now_ms ? env->now_ms() : 0u;
    GN.phase = 0;
    if (GN.what == GNB_REQ_LEAVE && why == GNB_W_UNREACH && RKS.lv < 6u) { RKS.lv++; RKS.retry_what = GNB_REQ_LEAVE; RKS.retry_at = now + 1000u; return; }      /* the hub client was busy (its report): the forfeit is sent again in a second, it must reach the server */
    if (GN.what == GNB_REQ_LEAVE || why == GNB_W_NOTFOUND || why == GNB_W_NOGN || why == GNB_W_SIGNIN) { b->exit = 1; return; }    /* the forfeit went (or failed for good: the server times the set out), or this is no set match: back to the hub */
    if (GN.what == GNB_REQ_ACTION && b->prep.open) { b->prep.busy = 0; b->prep.dirty = 1; }                                     /* a refused strike / pick: the next view lets the player press again */
    if (GN.what == GNB_REQ_STATE && b->scr == GNB_BUSY) { RKS.retry_what = GNB_REQ_STATE; RKS.retry_at = now + 2000u; }          /* the first view has not come: ask again in 2 s */
    else if (GN.what == GNB_REQ_STATE) { b->st_miss++; }
}
static void gn_fail(unsigned why)
{
    if (RKS.on) { rk_fail(why); return; }
    if (GN.what == GNB_REQ_CHAT) { GN.phase = 0; return; }              /* a chat fetch that fails is silent: the next poll asks again */
    if (GN.what == GNB_REQ_CHATSEND) { gnb_net_chat_fail(&G.gn, GNB_CW_OTHER); GN.phase = 0; return; }
    gnb_net_fail(&G.gn, GN.what, why);
    GN.phase = 0;
}
static void gn_issue(unsigned now)
{
    struct gnb *b = &G.gn;
    int r = -1;
    if (GN.what == GNB_REQ_CHAT || GN.what == GNB_REQ_CHATSEND) {
        mnc *c = g_ucfg.net;
        gnchat_init(&GCH);
        r = GN.what == GNB_REQ_CHAT ? gnchat_fetch(&GCH, &c->w, &c->io, now, (mnc_u32)b->chat_cur) : gnchat_preset(&GCH, &c->w, &c->io, now, b->chat_arg);
        if (r) gn_fail(GNB_W_UNREACH); else GN.phase = 2;
        return;
    }
    if (RKS.on) {                                                          /* the ranked set ops of the held match (the match id of the hub client's pairing) */
        mnc *c = g_ucfg.net;
        gnc_init(&GC, c);
        switch (GN.what) {
        case GNB_REQ_STATE: r = gnc_rk_state(&GC, now, c->match_id); break;
        case GNB_REQ_ACTION: r = gnc_rk_action(&GC, now, c->match_id, b->act, b->act_val, ((b->act == 4u || b->act == 8u) && b->act_cos != 0xFFu) ? b->act_cos : 0xFFu); b->act_cos = 0xFFu; break;
        case GNB_REQ_LEAVE: r = gnc_rk_status(&GC, now, c->match_id, 2u); break;      /* MATCH_STATUS abandoned: the set is lost, as leaving a ranked set always is */
        default: break;
        }
        if (r) gn_fail(GNB_W_UNREACH); else GN.phase = 2;
        return;
    }
    gnc_init(&GC, g_ucfg.net);
    GC.lv5 = (mnc_u8)(GNLS.lver && GNLS.lver <= 5u); GC.lv4 = (mnc_u8)(GNLS.lver && GNLS.lver <= 4u);      /* an older server stays asked in its own version (no failed v6 request every refresh) */
    if (GNLS.lver && GNLS.lver <= 5u) GC.vver = GNC_VIEW_V5;
    switch (GN.what) {
    case GNB_REQ_LIST: r = gnc_list_f(&GC, now, b->lpage, gnb_list_filter(b)); break;
    case GNB_REQ_JOIN: r = gnc_join(&GC, now, gnb_join_code(b), gnb_join_pin(b), GNB_CHAR_RANDOM); break;    /* no character yet: the portrait shows "?" until a pick */
    case GNB_REQ_CREATE: {
        const char *nm, *pin;
        unsigned fl, pol;
        gnb_create_args(b, &nm, &fl, &pol, &pin);
        r = gnc_create_rt(&GC, now, nm, fl, pol, pin, gnb_create_cap(b), GNB_CHAR_RANDOM, gnb_create_smode(b), gnb_create_type(b));      /* the Type row's choice (view v6), or against an older server the old Stages byte */
        break;
    }
    case GNB_REQ_STATE: r = gnc_state(&GC, now, b->lob.have ? (int)b->lob.rev : -1); break;
    case GNB_REQ_ACTION: r = (b->act == 4u && b->act_cos != 0xFFu) ? gnc_action_cos(&GC, now, b->act, b->act_val, b->act_cos) : gnc_action(&GC, now, b->act, b->act_val); b->act_cos = 0xFFu; break;
    case GNB_REQ_LEAVE: r = gnc_leave(&GC, now); break;
    case GNB_REQ_ROSTER: r = gnc_roster(&GC, now); break;
    default: break;
    }
    if (r) gn_fail(GNB_W_UNREACH); else GN.phase = 2;
}
