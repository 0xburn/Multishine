static void o_leave(void)
{
    unsigned i;
    unsigned char *b;
#ifdef GNB_MELEE
    gnbev_abort();                                           /* nothing of ours may stay reachable from the retail procs once this block is freed */
    frdev_abort();
    gntev_abort();
#endif
    present_free();
    sgu_close(&U);                                           /* aborts a running check or download and frees the staging buffer */
    sgr_close(&G.sr);                                        /* Send Slippi Login: abort, wipe the key, free the block */
#ifdef SG_UPDHOST
    if (SC.st != SGC_IDLE) sr_abort(0);                      /* a command check in flight: dropped */
    b = (unsigned char *)&SC; for (i = 0; i < sizeof SC; i++) b[i] = 0;
#endif
    b = (unsigned char *)&U; for (i = 0; i < sizeof U; i++) b[i] = 0;
#if SG_LAB
    if (g_tcp_ready && g_tls_state == 2 && PR.phase != SDPROBE_DONE && PR.phase != SDPROBE_FAILED) { sdsec_close(&PR.sec); if (PR.h >= 0) sdtcp_abort(&TCP, PR.h); }
    if (g_tcp_ready && g_dg_h >= 0) sdtcp_abort(&TCP, g_dg_h);
    if (g_tcp_ready) { env->net->tcp_rx = 0; env->net->tcp_poll = 0; env->net->tcp = 0; }       /* the resident stack stops calling into this image */
    b = (unsigned char *)&PR; for (i = 0; i < sizeof PR; i++) b[i] = 0;      /* TLS keys and transcript */
    for (i = 0; i < sizeof g_rx; i++) g_rx[i] = 0;
    for (i = 0; i < sizeof g_tx; i++) g_tx[i] = 0;
    b = (unsigned char *)&LPOOL; for (i = 0; i < sizeof LPOOL; i++) b[i] = 0;
    for (i = 0; i < sizeof g_dg_buf; i++) g_dg_buf[i] = 0;
    g_tls_state = 0; g_tcp_ready = 0;
#endif
    b = (unsigned char *)&G; for (i = 0; i < sizeof G; i++) b[i] = 0;        /* the entropy test's pool copy */
    b = qr_tex; for (i = 0; i < SG_QR_TEX_BYTES; i++) b[i] = 0;
}

