/* the match loop: the hand-off block of the resident hub client (mnc gn_*, kept across a hub overlay reload) */
static int gn_block_ok(const mnc *c) { return c && c->gn_magic == MNC_GN_MAGIC; }
/* a Grandmaster set's hand-off: no room name, the ranked-set flag, and a state the menu scene may find it in (RKSET after the pairing or a played game; SEARCH / DONE when a game's report did not arrive) */
static int rk_hand_ok(const mnc *c)
{
    return gn_block_ok(c) && !c->gn_room[0] && (c->gn_room[MNC_RK_FLAGS_AT] & MNC_RK_FLAG) != 0u
           && (c->gn_state == MNC_GN_RKSET || c->gn_state == MNC_GN_SEARCH || c->gn_state == MNC_GN_DONE);
}
static void rk_release(mnc *c)                                              /* the set is over for this console: the hand-off block is idle again (the engine's watch capability bit stays) */
{
    unsigned i;
    if (!gn_block_ok(c)) return;
    c->gn_state = MNC_GN_NONE;
    for (i = 0; i < 19u; i++) if (i != 15u && i != 16u) c->gn_room[i] = 0;                 /* (15 / 16: the resident engine's screen-cover capability and flag, hub_soc.c GP_CAP / GP_COVER, are not ours to clear) */
    c->gn_room[MNC_RK_FLAGS_AT] &= GNS_RF_CAP_WATCH;
}
/* THE HAND-OFF COVER (the review page's "Event Match menu flashes between the prep and the game"): when the prep screen closes for a game the Main Menu's Event Match screen showed for a
   second or two before the character screen's cover came up.  Black from here (VISetBlack + VIFlush, as the Friends Z press does) and flag 4 = "held until the character screen starts": the resident engine
   (gns_res.c gns_cover_tick) turns it into the usual cover there, which lifts when the match loads.  An engine that does not know the value lifts it at its next pass (nothing stays black). */
static void gn_cover_hold(mnc *c)
{
#ifdef GNB_MELEE
    if (!gn_block_ok(c) || c->gn_room[GNS_ROOM_CAP] != GNS_CAP_MAGIC) return;      /* (only an engine that lifts the cover) */
    ((void (*)(int))0x80350100u)(1);
    ((void (*)(void))0x8034FF78u)();
    c->gn_room[GNS_ROOM_COVER] = 4u;
#else
    (void)c;
#endif
}
/* the next game is decided (gnb_rk.c gnrk_view): arm the character screen's lock-in with the game's character, costume and stage; the browser closes and the menu opens the character screen (ml_glue.c go_gn_play) */
static void rk_arm(struct gnb *b, mnc *c)
{
    if (!gn_block_ok(c)) return;
    if (b->rk.ch <= 26u) { c->gn_room[GNS_ROOM_PICK] = (unsigned char)(b->rk.ch + 1u); c->gn_room[GNS_ROOM_COSTUME] = (unsigned char)(b->rk.cos & 15u); }     /* the character the server knows (a counterpick); game 1: the pick of the ranked character screen stays */
    c->gn_room[MNC_RK_GAME_AT] = b->rk.game;
    c->gn_room[MNC_RK_STAGE_AT] = b->rk.stage;
    c->gn_state = MNC_GN_ARMED;
    gn_cover_hold(c);
    b->play = 2; b->exit = 1; b->msg = "Starting the game"; b->dirty |= GNB_D_PANEL;
}
static void rk_handoff(struct gnb *b, mnc *c)
{
    if (!RKS.on) {
        RKS.on = 1; RKS.retry_at = 0; RKS.lv_t = 0; RKS.sent = 0;
        gnrk_start(b, c->gn_room[MNC_RK_GAME_AT]);
        c->gn_state = MNC_GN_RKSET;                                        /* (back from a game, or the pairing itself) */
        b->resumed = 3;
        b->scr = GNB_BUSY; b->busy_what = GNB_REQ_STATE; b->req = GNB_REQ_STATE; b->lob.have = 0; b->msg = 0; b->dirty = GNB_D_ALL;
        return;
    }
    if (b->exit && b->play != 2) rk_release(c);                            /* left the set (forfeit, result seen): nothing of it stays armed */
}
static void gn_handoff(void)
{
    struct gnb *b = &G.gn;
    mnc *c = g_ucfg.net;
    unsigned i;
    if (G.scr != SG_GN || !b->live) return;
    if (RKS.on || (!b->resumed && rk_hand_ok(c))) { rk_handoff(b, c); return; }
    if (gn_block_ok(c) && c->gn_state == MNC_GN_LEFT) c->gn_state = MNC_GN_NONE;      /* the player left a watch on purpose: nothing to resume */
    if (!b->resumed && gn_block_ok(c) && c->gn_state != MNC_GN_NONE && c->gn_state != MNC_GN_DIRECT) {   /* (a Mano a mano hand-off is not a room's) */      /* back from a set (or its character screen): the room again, the block is spent */
        unsigned char af = c->gn_room[GNS_ROOM_FLAGS];                      /* (the watch's flags: the auto-watch bits, read before the block is spent) */
        c->gn_state = MNC_GN_NONE; c->gn_room[0] = 0; c->gn_room[GNS_ROOM_FLAGS] &= GNS_RF_CAP_WATCH;      /* (the engine's capability bit stays) */
        gnb_resume(b);
        if (af & GNS_RF_ZERR) { b->msg = "This console could not apply the room's rules"; b->dirty |= GNB_D_PANEL; }       /* Low-Mid Fun: the guard refused the patch, the set was void */
        if (af & GN_RF_AUTO) { b->autow = 1; b->autoc = (unsigned char)((af & GN_RF_CHAIN_MASK) >> GN_RF_CHAIN_SHIFT); }
        b->resumed = 2;                                                    /* 2 = resumed after a set (the RAM proof), 1 = looked, nothing to resume */
        return;
    }
    if (!b->resumed) b->resumed = 1;
    if (b->watch == 1) {                                                   /* "X: Last game": arm the watch hand-off, close the browser; the menu opens the character screen */
        if (!gn_block_ok(c) || !(c->gn_room[GNS_ROOM_FLAGS] & GNS_RF_CAP_WATCH)) { b->watch = 0; b->msg = "Update Multishine to watch"; b->dirty |= GNB_D_PANEL; return; }
        for (i = 0; "GNWATCH"[i]; i++) c->gn_room[i] = "GNWATCH"[i];
        c->gn_room[i] = 0;
        c->gn_room[GNS_ROOM_FLAGS] = (unsigned char)(GNS_RF_CAP_WATCH | GNS_RF_SPEC | (b->watch_live ? GNS_RF_LIVE : 0u) | (b->autow ? GN_RF_AUTO | ((unsigned)(b->autoc & 7u) << GN_RF_CHAIN_SHIFT) : 0u));
        c->gn_state = MNC_GN_WATCH;
        b->watch = 2;
        b->exit = 1;
        return;
    }
    if (b->play == 1) {                                                    /* both picked: arm the room search, close the browser; the menu opens the character screen */
        if (!gn_block_ok(c)) { b->play = 2; b->msg = "Update Multishine to play"; b->dirty |= GNB_D_PANEL; return; }   /* an older resident: no hand-off block */
        for (i = 0; i + 1u < sizeof c->gn_room && b->play_name[i]; i++) c->gn_room[i] = b->play_name[i];
        c->gn_room[i] = 0;
        /* (the name is GN + 4-digit room code + S + set (< 10,000) + G + game = 13 characters at most; the room NAME a player types never goes into the block and the server cuts it to 12: tests/test_ms_roomtypes_rooms.py HandoffStageByte ties this to MNC_GN_STAGE_AT) */
        if (i <= 13u) c->gn_room[MNC_GN_STAGE_AT] = (unsigned char)((b->lob.v3 && b->lob.stage != 0xFFu) ? b->lob.stage : 0u);   /* the game's stage as the room server decided it (drawn, struck or picked): byte 14, behind a name of at most 13 characters; the resident takes it as the match's only stage */
        c->gn_room[GNS_ROOM_FLAGS] = (unsigned char)((c->gn_room[GNS_ROOM_FLAGS] & GNS_RF_CAP_WATCH) | (gnb_upload_room(b->lob.rflags, b->lob.stadium) ? GNS_RF_SPEC : 0u) | (g_gn_frozen ? GNS_RF_FROZEN : 0u) | (GNLS.rt && b->lob.v6 ? GNS_RF_CHARS : 0u) | (b->lob.v6 && b->lob.rtype == GNB_RT_LOWMID ? GNS_RF_ZELDA : 0u) | (b->lob.v6 && b->lob.rtype == GNB_RT_WILD_CRAZY ? GNS_RF_ITEMS : 0u));   /* a spectatable room (Frozen Stadium policy): the match-time uploader may run; Low-Mid Fun: the engine applies the Zelda no-transform patch for the set whatever the room's spectate setting */
        {   /* the room pick carries over: the resident engine selects this character and costume on the character screen and presses START (gns_res.c gns_pick_tick) */
            unsigned s = b->lob.side < 2u ? b->lob.side : 0u, ch = b->pick_mine < 27u ? b->pick_mine : b->lob.side_char[s], co = (b->pick_mine < 26u) ? b->pick_cos[b->pick_mine] : 0u;      /* a pick that timed out: the view's character, costume 1 */
            if (ch >= GNB_PICK_N - 1u && b->lob.side_char[s] < GNB_PICK_N - 1u) { ch = b->lob.side_char[s]; co = 0u; }      /* Random: the room server resolved it (a restricted room: Low-Mid Fun, Ditto Dojo) and the view carries the fighter; the character screen's own Random could land on an excluded one and void the game */
            if (ch < GNB_PICK_N - 1u && !gnb_cell_ok(b, ch)) { for (ch = 0u; ch < GNB_PICK_N - 1u && !gnb_cell_ok(b, ch); ch++) { } co = 0u; }      /* never hand an excluded fighter over (a stale pick): the first allowed one */
            c->gn_room[GNS_ROOM_PICK] = (unsigned char)(ch <= 26u ? ch + 1u : 0u);
            c->gn_room[GNS_ROOM_COSTUME] = (unsigned char)(co & 15u);
        }
        c->gn_state = MNC_GN_ARMED;
        gn_cover_hold(c);
        b->play = 2;
        b->exit = 1;
    }
}
static void copy_n(char *d, const char *s, unsigned max) { unsigned q = 0; while (s[q] && q < max) { d[q] = s[q]; q++; } d[q] = 0; }
