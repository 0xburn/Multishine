/* Host test of the bracket tree window (gnt_tree.c) on the demo cups (gnt_demo.c): every (side, round, cursor) of a 4, 16 and 64 cup gives a window whose columns, links and rows are sane;
   the structure of the demo bracket equals the server's (tests/gnt_tree_struct.txt, generated by tools from ms_tourney.Bracket); an ASCII picture of the windows goes
   to the file named by argv[1] (the docs' tree figures).  Mock data only. */
#include <stdio.h>
#include <string.h>
#include <stdlib.h>
#include "../gnt.h"
#include "../gnt_tree.h"
#include "../gnt_demo.h"

static int fails;
#define CHECK(c) do { if (!(c)) { printf("FAIL %s:%d: %s\n", __FILE__, __LINE__, #c); fails++; } } while (0)

static void draw(FILE *f, const struct gnt *g, const struct gnt_tw *w)
{
    char line[8 * 4 + 1][80];
    unsigned c, k, y, x;
    char t[32];
    for (y = 0; y < 17u; y++) { memset(line[y], ' ', 79); line[y][79] = 0; }
    for (c = 0; c < w->nc; c++) {
        gnt_round_title(g, w->side[c], w->rnd[c], t);
        for (x = 0; t[x] && x < 24u; x++) line[0][c * 26u + x] = t[x];
        for (k = 0; k < w->n[c]; k++) {
            const struct gnt_match *m = &g->b_m[w->mi[c][k]];
            unsigned yy = 1u + w->y[c][k] * 2u - 1u;       /* two lines per plate: row yy and yy + 1 */
            char a[20], b[20];
            snprintf(a, sizeof a, "%c%-9.9s %c", (c == 0u && k == w->cur) ? '>' : ' ', m->a == GNT_NONE ? "?" : g->b_name[m->a], m->state == GNT_M_DONE ? (m->win == 1u ? 'W' : 'l') : m->state == GNT_M_CALLED ? 'C' : m->state == GNT_M_LIVE ? '*' : ' ');
            snprintf(b, sizeof b, " %-9.9s %c", m->b == GNT_NONE ? "?" : g->b_name[m->b], m->state == GNT_M_DONE ? (m->win == 2u ? 'W' : 'l') : ' ');
            for (x = 0; a[x]; x++) line[yy][c * 26u + x] = a[x];
            for (x = 0; b[x]; x++) line[yy + 1u][c * 26u + x] = b[x];
            if (w->lk[c][k] != 0xFFu) line[yy][c * 26u + 14u] = '-', line[yy][c * 26u + 15u] = '>';
        }
    }
    for (y = 0; y < 17u; y++) { unsigned e = 79; while (e && line[y][e - 1] == ' ') e--; line[y][e] = 0; fprintf(f, "%s\n", line[y]); }
}

int main(int argc, char **argv)
{
    static struct gnt g;
    static const unsigned SIZES[3] = { 4, 16, 64 };
    unsigned si, side, rnd, sel, c, k;
    FILE *out = argc > 1 ? fopen(argv[1], "w") : 0;
    unsigned windows = 0;
    for (si = 0; si < 3u; si++) {
        unsigned S = SIZES[si], done = gnt_demo_done(si + 1u), me = 1;
        memset(&g, 0, sizeof g);
        gnt_demo_bracket(&g, S, done, me);
        CHECK(g.b_have && g.b_size == S && g.b_rounds == gnt_round_count(S));
        { unsigned n = 0, i; for (i = 0; i < GNT_MATCHES; i++) if (g.b_m[i].mid) n++; CHECK(n == 2u * S - 1u); }          /* S - 1 winners + S - 2 losers + the grand final and its reset = 2S - 1 */
        for (side = 0; side < 3u; side++)
            for (rnd = 1; rnd <= 12u; rnd++) {
                unsigned cnt = 0, i;
                for (i = 0; i < GNT_MATCHES; i++) if (g.b_m[i].mid && g.b_m[i].side == side && g.b_m[i].round == rnd) cnt++;
                if (!cnt) continue;
                for (sel = 0; sel < cnt; sel++) {
                    struct gnt_tw w;
                    g.b_side = (unsigned char)side; g.b_round = (unsigned char)rnd; g.b_sel = (unsigned char)sel;
                    CHECK(gnt_tree_layout(&g, &w) == 1u);
                    windows++;
                    CHECK(w.nc >= 1u && w.nc <= GNT_TW_COLS && w.n[0] >= 1u && w.n[0] <= GNT_TW_ROWS);
                    CHECK(w.cur < w.n[0] && w.pod >= 1u && w.pod <= w.pods && w.pods == (cnt + 3u) / 4u);
                    CHECK(w.pod == sel / 4u + 1u);
                    for (c = 0; c < w.nc; c++) {
                        CHECK(w.side[c] == g.b_m[w.mi[c][0]].side && w.rnd[c] == g.b_m[w.mi[c][0]].round);
                        for (k = 0; k < w.n[c]; k++) {
                            CHECK(w.mi[c][k] < GNT_MATCHES && g.b_m[w.mi[c][k]].mid);
                            CHECK(w.y[c][k] >= 1u && w.y[c][k] <= 7u);
                            if (k) CHECK(w.y[c][k] >= w.y[c][k - 1u] + 2u);                         /* plates do not overlap: one unit is half a plate pitch */
                            if (c + 1u < w.nc) { CHECK(w.lk[c][k] == 0xFFu || w.lk[c][k] < w.n[c + 1u]); if (w.lk[c][k] != 0xFFu) CHECK(g.b_m[w.mi[c][k]].next_win - 1u == w.mi[c + 1u][w.lk[c][k]]); }
                        }
                    }
                    if (w.nc >= 2u) { for (k = 0; k < w.n[0]; k++) if (g.b_m[w.mi[0][k]].next_win) CHECK(w.lk[0][k] != 0xFFu); }
                    if (out && sel % 4u == 0u && ((S == 16u && (rnd == 1u || (side == GNT_SIDE_L && rnd == 3u))) || (S == 64u && side == GNT_SIDE_W && rnd <= 2u && sel < 8u) || (S == 4u))) {
                        fprintf(out, "== cup %u, side %u round %u, pod %u of %u ==\n", S, side, rnd, w.pod, w.pods);
                        draw(out, &g, &w); fprintf(out, "\n");
                    }
                }
            }
        /* winners: a cup of S has S/2 matches in round 1 and the four-match pods carry on to a two-match and a one-match column */
        { struct gnt_tw w; g.b_side = GNT_SIDE_W; g.b_round = 1; g.b_sel = 0; CHECK(gnt_tree_layout(&g, &w) && w.nc == (S == 4u ? 3u : 3u) && w.n[0] == (S == 4u ? 2u : 4u));
          if (S >= 16u) CHECK(w.n[1] == 2u && w.n[2] == 1u && w.y[0][0] == 1u && w.y[1][0] == 2u && w.y[1][1] == 6u && w.y[2][0] == 4u); }
        /* exactly one match is yours-called, one live; finished matches carry a winner */
        { unsigned i, called = 0, live = 0, fin = 0; for (i = 0; i < GNT_MATCHES; i++) { if (!g.b_m[i].mid) continue; if (g.b_m[i].state == GNT_M_CALLED) called++; if (g.b_m[i].state == GNT_M_LIVE) live++; if (g.b_m[i].state == GNT_M_DONE) { fin++; CHECK(g.b_m[i].win == 1u || g.b_m[i].win == 2u); } }
          CHECK(called <= 1u && live == 1u && fin <= done); }
    }
    CHECK(windows > 150u);
    { struct gnt g2; unsigned i; memset(&g2, 0, sizeof g2); { struct gnt_tw w; CHECK(gnt_tree_layout(&g2, &w) == 0u); } (void)i; }
    if (out) fclose(out);
    printf(fails ? "gnt_tree_test: %d FAILED\n" : "gnt_tree_test: all passed (windows checked)\n", fails);
    return fails ? 1 : 0;
}
