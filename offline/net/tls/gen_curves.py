def primes(n):
    out, k = [], 2
    while len(out) < n:
        if all(k % p for p in out): out.append(k)
        k += 1
    return out


def iroot(x, r):
    lo, hi = 0, 1 << ((x.bit_length() // r) + 2)
    while lo < hi:
        mid = (lo + hi + 1) // 2
        if mid ** r <= x: lo = mid
        else: hi = mid - 1
    return lo


def frac64(p, r):
    """first 64 bits of the fractional part of p^(1/r)"""
    v = iroot(p << (64 * r), r)
    return v & ((1 << 64) - 1)


def pairs(vals):
    return ", ".join("0x%08xu, 0x%08xu" % (v >> 32, v & 0xffffffff) for v in vals)


def main():
    print("/* Generated by gen_curves.py from the SEC 2 / FIPS 186-4 curve parameters; big-endian bytes. */")
    for k, v in CURVES.items():
        for f in ("p", "n", "b", "gx", "gy"):
            bs = v[f].to_bytes(v["sz"], "big")
            print("static const sdpk_u8 %s_%s[%d] = {%s};" % (k, f.upper(), v["sz"], ", ".join("0x%02x" % x for x in bs)))
    pr = primes(80)
    print("/* SHA-512 / SHA-384 constants (FIPS 180-4 4.2.3, 5.3.4, 5.3.5) as (high, low) 32-bit pairs, computed from the primes */")
    print("static const sdpk_u32 SHA512_K[160] = {%s};" % pairs([frac64(p, 3) for p in pr]))
    print("static const sdpk_u32 SHA512_H[16] = {%s};" % pairs([frac64(p, 2) for p in pr[:8]]))
    print("static const sdpk_u32 SHA384_H[16] = {%s};" % pairs([frac64(p, 2) for p in pr[8:16]]))


if __name__ == "__main__":
    main()
