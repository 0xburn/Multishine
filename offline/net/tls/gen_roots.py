"""Generate sdroots.c (the console's trust anchors) from the PEM files of the public root certificates.
Each anchor keeps only the subject Name (raw DER, byte-compared against a certificate's issuer) and the public key (RSA n,e or EC point).
Usage: gen_roots.py [--pull BUNDLE.pem 'CN=...' ...]   (copies the named roots out of a system bundle into roots/)
       gen_roots.py > sdroots.c                        (regenerate; tests/run_tests.sh compares the file with this output)
Update story: add or remove a PEM, run this, rebuild; anchors ship with the overlay, so a new root
needs a normal update.  Roots we ship are public CA certificates; no private data is involved."""
import pathlib, re, sys
from cryptography import x509
from cryptography.hazmat.primitives import serialization
from cryptography.hazmat.primitives.asymmetric import rsa, ec

HERE = pathlib.Path(__file__).resolve().parent
ROOTS = HERE / "roots"


def tlv(b, i):
    tag = b[i]; l = b[i + 1]; i += 2
    if l & 0x80:
        n = l & 0x7f; l = int.from_bytes(b[i:i + n], "big"); i += n
    return tag, i, l           # content starts at i, length l


def subject_der(cert_der):
    _, i, l = tlv(cert_der, 0)                    # Certificate
    _, i, l = tlv(cert_der, i)                    # TBS
    j = i
    t, a, la = tlv(cert_der, j)                   # version [0]
    if t == 0xa0: j = a + la
    for _ in range(2):                            # serial, signature alg
        t, a, la = tlv(cert_der, j); j = a + la
    t, a, la = tlv(cert_der, j); j = a + la       # issuer
    t, a, la = tlv(cert_der, j); j = a + la       # validity
    t, a, la = tlv(cert_der, j)                   # subject
    return cert_der[j:a + la]


def arr(name, data):
    return "static const unsigned char %s[%d] = {%s};" % (name, len(data), ", ".join("0x%02x" % x for x in data))


def pull(bundle, names):
    ROOTS.mkdir(exist_ok=True)
    data = open(bundle).read()
    for m in re.finditer(r"-----BEGIN CERTIFICATE-----.*?-----END CERTIFICATE-----", data, re.S):
        try: c = x509.load_pem_x509_certificate(m.group(0).encode())
        except Exception: continue
        cn = c.subject.rfc4514_string()
        if cn in names:
            fn = ROOTS / (re.sub(r"[^A-Za-z0-9]+", "_", cn.split(",")[0].replace("CN=", "")).strip("_") + ".pem")
            fn.write_text(c.public_bytes(serialization.Encoding.PEM).decode()); print("pulled", cn, "->", fn.name, file=sys.stderr)


def main():
    if len(sys.argv) > 2 and sys.argv[1] == "--pull":
        pull(sys.argv[2], set(sys.argv[3:])); return
    out = ["/* Generated by gen_roots.py from offline/net/tls/the roots/ PEM files: do not edit.  Trust anchors for the console WebPKI client (sdx509). */",
           '#include "sdx509.h"']
    ents = []
    for n, f in enumerate(sorted(ROOTS.glob("*.pem"))):
        c = x509.load_pem_x509_certificate(f.read_bytes())
        der = c.public_bytes(serialization.Encoding.DER)
        out.append("/* %s (expires %s) */" % (c.subject.rfc4514_string(), c.not_valid_after_utc.date()))
        out.append(arr("dn%d" % n, subject_der(der)))
        pk = c.public_key()
        if isinstance(pk, rsa.RSAPublicKey):
            nn = pk.public_numbers().n.to_bytes((pk.public_numbers().n.bit_length() + 7) // 8, "big")
            ee = pk.public_numbers().e.to_bytes((pk.public_numbers().e.bit_length() + 7) // 8, "big")
            out.append(arr("k%d" % n, nn)); out.append(arr("e%d" % n, ee))
            ents.append("    { dn%d, sizeof dn%d, SDX_KEY_RSA, k%d, sizeof k%d, e%d, sizeof e%d }" % (n, n, n, n, n, n))
        else:
            assert isinstance(pk, ec.EllipticCurvePublicKey)
            pt = pk.public_bytes(serialization.Encoding.X962, serialization.PublicFormat.UncompressedPoint)
            kt = {"secp256r1": "SDX_KEY_EC256", "secp384r1": "SDX_KEY_EC384"}[pk.curve.name]
            out.append(arr("k%d" % n, pt))
            ents.append("    { dn%d, sizeof dn%d, %s, k%d, sizeof k%d, 0, 0 }" % (n, n, kt, n, n))
    out.append("const struct sdx_anchor sdx_roots[%d] = {\n%s\n};" % (len(ents), ",\n".join(ents)))
    out.append("const sdx_u32 sdx_nroots = %d;" % len(ents))
    print("\n".join(out))


if __name__ == "__main__":
    main()
