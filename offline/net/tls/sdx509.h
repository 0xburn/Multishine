#ifndef SDX509_H
#define SDX509_H
/* sdx509: a deliberately small, bounded X.509 (RFC 5280) reader and chain checker for the console TLS client's WebPKI mode
   .  No heap, no recursion, no libc; every read is checked against the buffer end; DER is parsed
   strictly (definite minimal lengths, single-byte tags).  Supported: v3 certificates, RSA (2048..4096) and ECDSA P-256 / P-384 keys,
   signatures sha256/sha384 with RSA PKCS#1 v1.5 or ECDSA; basicConstraints, keyUsage, extendedKeyUsage, subjectAltName; every other
   CRITICAL extension makes the certificate unacceptable (fail closed).  NOT supported on purpose: name constraints, policy constraints,
   revocation (CRL/OCSP), CN fallback for host names, IP-address names, Ed25519/RSA-PSS certificate signatures.
   Trust is a list of anchors (subject name + public key) compiled in (sdroots.c); validity dates are checked against a caller-supplied
   Unix time (the console has no clock: the time comes from our own authenticated server). */
#include "sdpk.h"

typedef sdpk_u8 sdx_u8;
typedef sdpk_u32 sdx_u32;

#define SDX_KEY_NONE 0
#define SDX_KEY_RSA 1
#define SDX_KEY_EC256 2
#define SDX_KEY_EC384 3

#define SDX_SIG_NONE 0
#define SDX_SIG_RSA_SHA256 1
#define SDX_SIG_RSA_SHA384 2
#define SDX_SIG_ECDSA_SHA256 3
#define SDX_SIG_ECDSA_SHA384 4

#define SDX_E_PARSE (-1)        /* malformed DER or certificate structure */
#define SDX_E_UNSUPPORTED (-2)  /* well-formed but outside what we accept (key type, version, algorithm) */
#define SDX_E_CRITICAL (-3)     /* unknown critical extension */
#define SDX_E_EXPIRED (-4)      /* not yet valid or expired at the given time */
#define SDX_E_NOTIME (-5)       /* no trusted time available and the caller did not allow skipping validity */
#define SDX_E_HOST (-6)         /* subjectAltName does not cover the host name */
#define SDX_E_CA (-7)           /* an issuer in the chain is not a CA / may not sign certificates / path length exceeded; EKU/KU refuse the use */
#define SDX_E_UNTRUSTED (-8)    /* no path to a trust anchor */
#define SDX_E_SIG (-9)          /* a signature in the chain does not verify */

#define SDX_MAX_CHAIN 4         /* leaf + up to 3 intermediates before an anchor */
#define SDX_MAX_CERT 4096       /* any single certificate larger than this is refused */

struct sdx_cert {
    const sdx_u8 *der; sdx_u32 der_len;
    const sdx_u8 *tbs; sdx_u32 tbs_len;                 /* the signed bytes: the TBSCertificate TLV including its header */
    const sdx_u8 *issuer; sdx_u32 issuer_len;           /* Name TLVs, byte-compared */
    const sdx_u8 *subject; sdx_u32 subject_len;
    sdx_u32 not_before, not_after;                      /* Unix seconds */
    sdx_u8 key_type, sig_alg, is_ca, has_bc, has_ku, ku_sign, ku_cert, has_eku, eku_server;
    int pathlen;                                        /* -1: none */
    const sdx_u8 *key; sdx_u32 key_len;                 /* RSA: modulus (no leading zero); EC: 04||X||Y */
    const sdx_u8 *key_e; sdx_u32 key_e_len;
    const sdx_u8 *sig; sdx_u32 sig_len;                 /* signature bytes (BIT STRING content) */
    const sdx_u8 *san; sdx_u32 san_len;                 /* GeneralNames content */
};

/* Parse one certificate.  Returns 0 or a SDX_E_* code.  Pointers in *c point into der. */
int sdx_parse(struct sdx_cert *c, const sdx_u8 *der, sdx_u32 len);
/* Does the subjectAltName cover `host` (dNSName, case-insensitive, one left-most wildcard label)?  1 or 0. */
int sdx_host_match(const struct sdx_cert *c, const char *host);
/* seconds since 1970 for a civil date (UTC), 0 if outside 1970..2105 */
sdx_u32 sdx_unix_time(sdx_u32 y, sdx_u32 mo, sdx_u32 d, sdx_u32 h, sdx_u32 mi, sdx_u32 s);

struct sdx_anchor {
    const sdx_u8 *dn; sdx_u32 dn_len;                   /* subject Name TLV */
    sdx_u8 key_type;
    const sdx_u8 *key; sdx_u32 key_len;
    const sdx_u8 *key_e; sdx_u32 key_e_len;
};
/* Build an anchor from a parsed (self-signed root) certificate: for host tests and tools; production anchors are in sdroots.c. */
void sdx_anchor_from_cert(struct sdx_anchor *a, const struct sdx_cert *c);
extern const struct sdx_anchor sdx_roots[];             /* sdroots.c, generated by gen_roots.py */
extern const sdx_u32 sdx_nroots;

#define SDX_F_NO_TIME 1u        /* caller accepts the risk: skip validity dates when no trusted time exists (see the doc: never for secrets) */

struct sdx_chain {
    const struct sdx_anchor *anchors; sdx_u32 nanchors;
    const char *host; sdx_u32 now, flags;
    struct sdx_cert c[SDX_MAX_CHAIN];
    sdx_u32 n;                                          /* certificates in the path (those below the anchor) */
    sdx_u32 step;                                       /* signatures verified so far */
    const struct sdx_anchor *root;
};
/* Parse and policy-check the path: ders[0] is the leaf, then the intermediates in the order the server sent them.  Stops at the first
   certificate issued by an anchor.  Does NOT verify signatures: call sdx_chain_step n times.  Returns 0 or a SDX_E_* code. */
int sdx_chain_begin(struct sdx_chain *ch, const struct sdx_anchor *anchors, sdx_u32 nanchors, const char *host, sdx_u32 now, sdx_u32 flags,
                    const sdx_u8 *const *ders, const sdx_u32 *lens, sdx_u32 count);
/* One signature verification (one heavy operation).  Returns 0 = ok, more steps remain; 1 = ok and the chain is complete; or SDX_E_SIG / SDX_E_UNSUPPORTED. */
int sdx_chain_step(struct sdx_chain *ch, struct sdpk_ws *ws);
#endif
