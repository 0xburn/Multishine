"""gen_slp_tab: writes offline/seed/seed_slp_tab.h, the table the system-files builder's Slippi data build (seed_slp.c) checks its inputs against and builds the stock pack from.

  gen_slp_tab.py --disc RETAIL.iso --slippi-files <Slippi GameFiles/GALE01> [--out FILE] [--check]

The table holds only SIZES and CRC-32s of the five pack inputs (the retail file the delta is made against, the intended result) and the per-file encoder choices that tools/card/build_pack.py makes for
the stock pack (mdelta parameter set, entry mode).  No file content.  --check recomputes the choices (slow, the PC encoders) and compares them with the ones fixed here; without it the fixed ones are used.
"""
import argparse, os, sys, zlib

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.normpath(os.path.join(HERE, "..", ".."))
sys.path.insert(0, os.path.join(REPO, "tools", "card"))
sys.path.insert(0, os.path.join(REPO, "tools", "payload_pack"))
sys.path.insert(0, os.path.join(REPO, "offline", "cardloader"))
sys.path.insert(0, os.path.join(REPO, "offline", "iso"))
import mdelta  # noqa: E402
import apply_overlays  # noqa: E402

# (name, mode, mdelta params or None): what build_pack.py chooses for the stock pack, and the order it writes them (sorted by name).  mode: 4 = in place delta, 3 = delta, 1 = MSLZ of the whole file.
CHOICE = (("MnExtAll.usd", 4, (12, 4, 16)), ("MnMaAll.usd", 3, (16, 4, 32)), ("SdMenu.usd", 3, (16, 4, 24)), ("SdSlChr.usd", 3, (12, 4, 16)), ("slpCSS.dat", 1, None), ("MnSlMap.usd", 3, (16, 4, 32)))


# work units the build needs per entry (the progress bar's weights): `seed_slp_test build SLPDIR RETDIR OUT.gci` prints them ("work units per entry"); refresh after changing the encoders' unit costs
EST = {"MnExtAll.usd": 2890510, "MnMaAll.usd": 50904047, "SdMenu.usd": 4515324, "SdSlChr.usd": 119909, "slpCSS.dat": 171756646, "MnSlMap.usd": 15300000}


def crc(b):
    return zlib.crc32(b) & 0xFFFFFFFF


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--disc", default=os.environ.get("MULTISHINE_RETAIL_ISO"), required=False)
    ap.add_argument("--slippi-files", default=str(apply_overlays.DEFAULT_OVERLAYS))
    ap.add_argument("--out", default=os.path.join(HERE, "seed_slp_tab.h"))
    ap.add_argument("--check", action="store_true", help="re-derive the encoder choices with build_pack.py (minutes)")
    a = ap.parse_args(argv)
    import tempfile, shutil
    tmp = tempfile.mkdtemp(prefix="slptab-")
    try:
        errs, _ = apply_overlays.apply_all(a.disc, a.slippi_files, tmp, use_xdelta=False, only=set(n for n, _, _ in CHOICE), log=lambda *_: None)
        if errs:
            sys.exit("overlay decode/verify failed: " + "; ".join(errs))
        img = apply_overlays.gcm.Image(a.disc)
        rows = []
        for name, mode, prm in CHOICE:
            new = open(os.path.join(tmp, name), "rb").read()
            old = b""
            if prm:
                node, _, _ = img.lookup(name)
                old = node.src.read(img.stream)
            if prm:
                d = mdelta.encode(old, new, prm)
                dlen = len(d)
            else:
                dlen = len(new)
            dcap = min(len(new) + 64, max(dlen * 2, 65536))
            dcap = (dcap + 4095) // 4096 * 4096
            if mode == 4:
                dcap = 16384
            est = EST[name]
            rows.append((name, mode, prm or (0, 0, 0), len(old), crc(old) if prm else 0, len(new), crc(new), dcap, est))
            print("%-14s mode %d params %-12s old %8d new %8d mdelta %7d est %9d" % (name, mode, prm, len(old), len(new), dlen, est))
        if a.check:
            sys.path.insert(0, os.path.join(REPO, "tools", "card"))
            import build_pack
            files, retail = build_pack.load_files(a.disc, a.slippi_files, [r[0] for r in rows], None)
            gci, man = build_pack.make_pack(files, retail, {})
            for e, r in zip(man["entries"], rows):
                got = {"inplace": 4, "delta": 3, "mslz": 1}[e["mode"]]
                if e["name"] != r[0] or got != r[1]:
                    sys.exit("build_pack chooses %s for %s, the table says %d" % (e["mode"], e["name"], r[1]))
            print("encoder choices confirmed by build_pack.py (%d blocks)" % man["blocks"])
        img.close()
    finally:
        shutil.rmtree(tmp, ignore_errors=True)
    out = ["/* Copyright (C) 2026 Nigzel / Bjerreman. SPDX-License-Identifier: GPL-3.0-or-later */",
           "/* GENERATED by offline/seed/gen_slp_tab.py: sizes and CRC-32s only (no file content) of the stock pack inputs and the encoder choices of tools/card/build_pack.py.  Do not edit. */",
           "#ifndef SEED_SLP_TAB_H", "#define SEED_SLP_TAB_H",
           "#define SLP_M_MSLZ 1u", "#define SLP_M_DELTA 3u", "#define SLP_M_DELTA_IP 4u",
           "struct slp_tab { const char *name; unsigned mode, W, STEP, MINC, old_size, old_crc, new_size, new_crc, dcap, est; };",
           "static const struct slp_tab SLP_TAB[SLP_NENT_MAX] = {"]
    for name, mode, prm, osz, ocrc, nsz, ncrc, dcap, est in rows:
        out.append('    { "%s", %du, %du, %du, %du, %du, 0x%08Xu, %du, 0x%08Xu, %du, %du },' % (name, mode, prm[0], prm[1], prm[2], osz, ocrc, nsz, ncrc, dcap, est))
    out += ["};", "#endif", ""]
    open(a.out, "w").write("\n".join(out))
    print("wrote", a.out)
    return 0


if __name__ == "__main__":
    sys.exit(main())
