"""Makes offline/multishine/menus/ml/ml_font_tex.h: OUR font for the overlay text pages: the earlier image's face
(Aileron Regular as bundled with Pillow, public domain / CC0, double-struck 1 px for weight: archive/system-files builder-disc/offline/seed/gen_font.py) in four pixel sizes, ASCII 32..126, packed into
ONE I4 GX texture (8 x 8 texel tiles, two texels per byte, high nibble = left texel, as sg_qr_texture and ml_mark_tex.h) plus a glyph table.  The renderer draws
one quad per glyph at 1:1 (one texel = one frame-buffer pixel).  No Nintendo bytes: the face and every pixel are generated here.
   python3.14 -I make_ui_font.py [] [--png PREVIEW.png]"""
import os, sys
from PIL import Image, ImageDraw, ImageFont

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.normpath(os.path.join(HERE, "..", ".."))
OUT = os.path.join(REPO, "offline", "multishine", "menus", "ml", "ml_font_tex.h")
# (name, pixel size): the page rows are 18.5 px apart in the 480-line frame (26 rows), so body text is 17 px; titles keep the system-files builder's 26
SIZES = (("SMALL", 14), ("BODY", 17), ("BIG", 19), ("TITLE", 26))
TEX_W = 256
PAD = 1


def glyphs(size):
    f = ImageFont.load_default(size=size)
    asc, desc = f.getmetrics()
    out = []
    for c in range(32, 127):
        ch = chr(c)
        adv = int(round(f.getlength(ch))) + 1
        im = Image.new("L", (adv + 4, asc + desc + 2), 0)
        d = ImageDraw.Draw(im)
        for dx in (0, 1):
            d.text((1 + dx, asc), ch, font=f, fill=255, anchor="ls")
        bb = im.getbbox()
        if not bb:
            out.append({"adv": adv, "x0": 0, "y0": 0, "w": 0, "h": 0, "im": None})
            continue
        x0, y0, x1, y1 = bb
        out.append({"adv": adv, "x0": x0 - 1, "y0": y0, "w": x1 - x0, "h": y1 - y0, "im": im.crop(bb)})   # y0: rows below the line's top (ascent at asc)
    return out, asc, desc


SHAPES = (("DISC", 20, 20), ("PILL", 46, 20), ("SOLID", 8, 8), ("CAP", 26, 26), ("BCAP", 12, 12))      # CAP: the selected row's pill ends, halves of a 26 px disc; the footer's key badges (GUI pass: GameCube coloured buttons): a disc for one letter, a pill for Start; drawn in the key's colour


def shapes():
    out = []
    for name, w, h in SHAPES:
        if name == "SOLID":                                # one opaque patch: drawn bars and rectangles sample its middle (mlf_rect)
            out.append({"name": name, "adv": w, "x0": 0, "y0": 0, "w": w, "h": h, "im": Image.new("L", (w, h), 255)})
            continue
        k = 8
        im = Image.new("L", (w * k, h * k), 0)
        ImageDraw.Draw(im).rounded_rectangle([0, 0, w * k - 1, h * k - 1], radius=h * k // 2, fill=255)
        out.append({"name": name, "adv": w, "x0": 0, "y0": 0, "w": w, "h": h, "im": im.resize((w, h), Image.LANCZOS)})
    return out


def pack(sets, extra=()):
    """shelf packing, tallest first, into TEX_W wide; returns height (multiple of 8)"""
    items = [g for _, gs, _, _ in sets for g in gs if g["im"] is not None] + list(extra)
    items.sort(key=lambda g: -g["h"])
    x = y = shelf = 0
    for g in items:
        if x + g["w"] + PAD > TEX_W:
            x, y, shelf = 0, y + shelf + PAD, 0
        g["u"], g["v"] = x, y
        x += g["w"] + PAD
        shelf = max(shelf, g["h"])
    return (y + shelf + 7) // 8 * 8


def i4_tiles(img):
    w, h = img.size
    px = img.load()
    out = bytearray(w * h // 2)
    for ty in range(h):
        for tx in range(w):
            q = min(15, (px[tx, ty] + 8) // 17)
            tile = (ty >> 3) * (w >> 3) + (tx >> 3)
            at = tile * 32 + (ty & 7) * 4 + ((tx & 7) >> 1)
            out[at] |= (q << 4) if not (tx & 1) else q
    return bytes(out)


def main(a):
    out = a[0] if a and not a[0].startswith("--") else OUT
    png = a[a.index("--png") + 1] if "--png" in a else None
    sets = []
    for name, sz in SIZES:
        gs, asc, desc = glyphs(sz)
        sets.append((name, gs, asc, desc))
    shp = shapes()
    th = pack(sets, shp)
    if th > 256:
        sys.exit("the sheet needs %d rows: more than 256 (texture coordinates are u8.8 in the renderer, ml_font.h)" % th)
    th = 256                                     # a power of two: the renderer sends texel coordinates as u16 with 8 fraction bits (s = u / 256, t = v / 256), no float maths
    sheet = Image.new("L", (TEX_W, th), 0)
    for _, gs, _, _ in sets:
        for g in gs:
            if g["im"] is not None:
                sheet.paste(g["im"], (g["u"], g["v"]))
    for g in shp:
        sheet.paste(g["im"], (g["u"], g["v"]))
    tex = i4_tiles(sheet)
    if png:
        sheet.save(png)
    L = ["/* Copyright (C) 2026 Nigzel / Bjerreman. SPDX-License-Identifier: GPL-3.0-or-later */",
         "/* GENERATED by tools/brand/make_ui_font.py: do not edit.  Our font for the overlay text pages (docs/design/OWN_FONT_PAGES.md): Aileron Regular (CC0), double-struck,",
         " * sizes %s; ONE I4 texture %d x %d (8x8 tiles, high nibble = left texel), %d bytes; glyph table per size for ASCII 32..126. */" % (", ".join("%s %d px" % s for s in SIZES), TEX_W, th, len(tex)),
         "#ifndef ML_FONT_TEX_H", "#define ML_FONT_TEX_H",
         "#define MLF_TEX_W %du" % TEX_W, "#define MLF_TEX_H %du" % th, "#define MLF_TEX_BYTES %du" % len(tex), "#define MLF_NSIZES %du" % len(SIZES)]
    for i, (name, sz) in enumerate(SIZES):
        L.append("#define MLF_%s %du          /* %d px */" % (name, i, sz))
    L += ["struct mlf_g { unsigned char u, v_lo, v_hi, w, h; signed char x0; unsigned char y0, adv; };   /* texel box in the sheet (v = v_lo | v_hi << 8), offset from the pen (x0, y0 below the line top), advance */",
          "struct mlf_size { unsigned char px, asc, desc, line; };"]
    L.append("static const struct mlf_size mlf_sizes[%d] = { %s };" % (len(SIZES), ", ".join("{ %d, %d, %d, %d }" % (sz, asc, desc, asc + desc) for (_, sz), (_, _, asc, desc) in zip(SIZES, sets))))
    L.append("static const struct mlf_g mlf_glyph[%d][95] = {" % len(SIZES))
    for _, gs, _, _ in sets:
        row = []
        for g in gs:
            u, v = g.get("u", 0), g.get("v", 0)
            row.append("{%d,%d,%d,%d,%d,%d,%d,%d}" % (u, v & 255, v >> 8, g["w"], g["h"], g["x0"], g["y0"], g["adv"]))
        L.append("  { " + ",".join(row) + " },")
    L.append("};")
    L.append("#define MLF_NSHAPES %du" % len(shp))
    for i, g in enumerate(shp):
        L.append("#define MLF_S_%s %du        /* %d x %d */" % (g["name"], i + 1, g["w"], g["h"]))
    L.append("static const struct mlf_g mlf_shape[%d] = { %s };" % (len(shp), ", ".join("{%d,%d,%d,%d,%d,0,0,%d}" % (g["u"], g["v"] & 255, g["v"] >> 8, g["w"], g["h"], g["adv"]) for g in shp)))
    L.append("static const unsigned char mlf_tex[%d] __attribute__((aligned(32))) = {" % len(tex))
    for i in range(0, len(tex), 32):
        L.append("  " + ",".join("0x%02X" % b for b in tex[i:i + 32]) + ",")
    L += ["};", "#endif", ""]
    open(out, "w").write("\n".join(L))
    print("%s: texture %d x %d, %d bytes, sizes %s" % (out, TEX_W, th, len(tex), ", ".join(str(s) for _, s in SIZES)))


if __name__ == "__main__":
    main(sys.argv[1:])
