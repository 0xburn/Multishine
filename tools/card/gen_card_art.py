"""gen_card_art: offline/multishine/menus/upd/upd_art.h = OUR Melee-save art (banner 96x32 RGB5A3 + icon 32x32 CI8 + palette, 7680 bytes = file data 0x40..0x1E3F of a Melee save)
as one MSLZ stream, for the overlay art repair pass (upd_card.c upc_art_repair).  Source of the pixels: tools/release/save_art.py (no Nintendo bytes).
  gen_card_art.py            write the header        gen_card_art.py --check    exit 1 when the header on disk differs"""
import os, sys, zlib

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.normpath(os.path.join(HERE, "..", ".."))
sys.path.insert(0, os.path.join(REPO, "tools", "release")); sys.path.insert(0, os.path.join(REPO, "tools", "payload_pack"))
import save_art as S  # noqa: E402
import mslz  # noqa: E402

OUT = os.path.join(REPO, "offline", "multishine", "menus", "upd", "upd_art.h")


def raw():
    b, i, p = S.make_regions()
    return b + i + p


def render():
    r = raw()
    z = mslz.compress_best(r)
    assert mslz.decompress(z, len(r)) == r
    rows = []
    for k in range(0, len(z), 16):
        rows.append("    " + ",".join("0x%02x" % x for x in z[k:k + 16]) + ",")
    return "\n".join(["/* GENERATED by tools/card/gen_card_art.py from tools/release/save_art.py: do not edit.  Copyright (C) 2026 Nigzel / Bjerreman. SPDX-License-Identifier: GPL-3.0-or-later */",
                      "/* our Melee-save art (banner + icon + palette), 7680 bytes, MSLZ stream (offline/payload_pack/ms_lz.h) */",
                      "#ifndef UPD_ART_H", "#define UPD_ART_H",
                      "#define UPA_RAW 0x%xu" % len(r), "#define UPA_CRC 0x%08xu" % (zlib.crc32(r) & 0xFFFFFFFF), "#define UPA_Z %du" % len(z),
                      "static const unsigned char upa_z[UPA_Z] = {", *rows, "};", "#endif", ""])


if __name__ == "__main__":
    s = render()
    if "--check" in sys.argv:
        sys.exit(0 if os.path.exists(OUT) and open(OUT).read() == s else 1)
    open(OUT, "w").write(s); print("wrote", OUT)
