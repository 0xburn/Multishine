"""gen_card_text: offline/multishine/menus/upd/upd_text.h from offline/card_text.py (the one table of card file comment lines).
  gen_card_text.py            write the header
  gen_card_text.py --check    exit 1 when the header on disk differs"""
import os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.normpath(os.path.join(HERE, "..", ".."))
sys.path.insert(0, os.path.join(REPO, "offline"))
import card_text as T  # noqa: E402

OUT = os.path.join(REPO, "offline", "multishine", "menus", "upd", "upd_text.h")


def c(s):
    return '"' + s + '"'


def render():
    L = ["/* GENERATED by tools/card/gen_card_text.py from offline/card_text.py: do not edit.  Copyright (C) 2026 Nigzel / Bjerreman. SPDX-License-Identifier: GPL-3.0-or-later */",
         "/* the comment lines of every card file of ours and the exact older texts the overlay repair pass may replace (docs/design/CARD_ICONS.md section 3) */",
         "#ifndef UPD_TEXT_H", "#define UPD_TEXT_H",
         "#define UPT_ICON 1u          /* also gives a missing icon */", "#define UPT_NEED_B 2u        /* only while MultishineCodeB exists */",
         "#define UPT_MAXOLD %d" % max(len(T.KNOWN_OLD[k]) for k, _ in T.REPAIR),
         "struct upt_row { const char *name, *l1, *l2; unsigned flags, nold; const char *old[UPT_MAXOLD][2]; };",
         "static const struct upt_row upt_rows[] = {"]
    for suf, fl in T.REPAIR:
        a, b = T.TEXT[suf]
        olds = ", ".join("{%s, %s}" % (c(x), c(y)) for x, y in T.KNOWN_OLD[suf]) or "{0, 0}"
        L.append("    { %s, %s, %s, %du, %du, { %s } }," % (c(T.S + suf), c(a), c(b), fl, len(T.KNOWN_OLD[suf]), olds))
    L += ["};", "#define UPT_N %d" % len(T.REPAIR), "#endif", ""]
    return "\n".join(L)


if __name__ == "__main__":
    s = render()
    if "--check" in sys.argv:
        sys.exit(0 if os.path.exists(OUT) and open(OUT).read() == s else 1)
    open(OUT, "w").write(s)
    print("wrote", OUT)
