"""Melee single-player records as a compact C table for the CONSOLE-side seeding.

  melee_records_table.py [--data D] [--out FILE]           write the header (default offline/multishine/menus/ml/ml_rec_tab.h)
  melee_records_table.py --check [--data D] [--out FILE]   exit 1 if FILE is not what the dataset gives now (the host test runs this)

Same dataset selection as tools/card/melee_records.py apply (its function is reused, not copied): real-time rows only, resolved NTSC rows only,
PAL stand-ins and unresolved conflicts skipped.  Per SELKIND slot (0..24): Target Test best in FRAMES (0 = no record) and Home-Run distance in
CENTIMETRES (0 = no record), units exactly as the host tool writes them (frames chosen so the on-screen centiseconds equal the published ones,
metres -> cm capped at 345,850).  The header is generated and committed like ml_table.h (the MANIFEST stages it next to ml_set.c); rebuild it
whenever docs/data/melee_records.json changes.  Stdlib only."""
import argparse
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import melee_records as R   # noqa: E402

DEFAULT_OUT = os.path.normpath(os.path.join(HERE, "..", "..", "offline", "multishine", "menus", "ml", "ml_rec_tab.h"))


def table(data=None):
    ds = R.load_dataset(data)
    tf = [0] * R.NSLOT
    hc = [0] * R.NSLOT
    for s, sec in ds["rows"]["target"].items():
        tf[s] = R.frames_from_seconds(sec)
    for s, m in ds["rows"]["hrc"].items():
        hc[s] = R.cm_from_metres(m)
    for s in range(R.NSLOT):
        if not 0 <= tf[s] < 0x10000:
            raise R.RecError("slot %d: Target Test frames %d do not fit u16" % (s, tf[s]))
    return ds, tf, hc


def render(ds, tf, hc):
    ev = ds["rows"].get("events", {})
    out = ["/* GENERATED by tools/card/melee_records_table.py from docs/data/melee_records.json (%s). Do not edit; rebuild with that tool." % ds["version"],
           "   Per SELKIND slot: Target Test best in frames (0 = none), Home-Run distance in centimetres (0 = none).  Real-time, resolved NTSC rows only.",
           "   Copyright (C) 2026 Nigzel / Bjerreman. SPDX-License-Identifier: GPL-3.0-or-later */",
           "#ifndef ML_REC_TAB_H", "#define ML_REC_TAB_H",
           "#define MREC_DATA_SHA1 \"%s\"" % ds["sha1"], "#define MREC_NSLOT %d" % R.NSLOT,
           "static const unsigned short mrec_target[MREC_NSLOT] = {"]
    for s in range(R.NSLOT):
        out.append("    %d%s /* %d %s%s */" % (tf[s], "," if s < R.NSLOT - 1 else "", s, R.SELKIND[s], (" " + R.display_time(tf[s])) if tf[s] else ""))
    out.append("};")
    out.append("static const unsigned long mrec_hrc[MREC_NSLOT] = {")
    for s in range(R.NSLOT):
        out.append("    %dUL%s /* %d %s%s */" % (hc[s], "," if s < R.NSLOT - 1 else "", s, R.SELKIND[s], (" " + R.feet_text(hc[s])) if hc[s] else ""))
    out.append("};")
    out.append("/* Event Matches by SAVE index k (gm_803DF918 order): best in frames (time events) or KO count (KO events), 0 = none.  Human real-time, TASVideos page (docs/data/melee_records_tasvideos.json). */")
    out.append("#define MREC_NEVENT %d" % R.EV_N)
    out.append("static const unsigned long mrec_event[MREC_NEVENT] = {")
    for k in range(R.EV_N):
        v = ev.get(k)
        n = R.EVENT_INDEX.index(k) + 1
        w = 0 if v is None else (int(v[0]) if v[1] else min(R.frames_from_seconds(v[0]), R.EV_CAP_FRAMES))
        out.append("    %dUL%s /* k=%d event %d%s */" % (w, "," if k < R.EV_N - 1 else "", k, n, (" " + ("%d KOs" % w if v[1] else R.display_time(w))) if v else ""))
    out.append("};")
    out.append("#endif")
    return "\n".join(out) + "\n"


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--data")
    ap.add_argument("--out", default=DEFAULT_OUT)
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args(argv)
    try:
        text = render(*table(a.data))
    except R.RecError as x:
        sys.stderr.write("error: %s\n" % x)
        return 2
    if a.check:
        try:
            cur = open(a.out).read()
        except OSError:
            cur = None
        if cur != text:
            sys.stderr.write("%s is not current: run tools/card/melee_records_table.py\n" % a.out)
            return 1
        print("current: " + a.out)
        return 0
    with open(a.out, "w") as f:
        f.write(text)
    print("wrote %s" % a.out)
    return 0


if __name__ == "__main__":
    sys.exit(main())
