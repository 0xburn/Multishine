"""Title tab strips of the Friends screen (the retail Event Match tab reads "Friends", the parent tab "Main Menu"): writes
offline/multishine/menus/sign/frd_tab_art.h with the two strips ALREADY in the GX tile order of the retail tab images (168 x 28 I4 padded to 32 rows, 8 x 8 tiles,
2688 bytes), so the overlay (frd_ev.c) copies them over the live images with no conversion code.  Same renderer as the hub's strips (menu_label_art.render_tab).

  python3 tools/frd_tab_art.py []
"""
import os, sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import menu_label_art as m

KB_TAB = "Main Menu"                 # the add-friend keyboard's left tab (variant Z "Main Menu", variant A "More"; was "Friends")
STRIPS = [("main", "Main Menu", 24), ("friends", KB_TAB, 29)]          # (name, text, font px): 29 = cap height 21.5 rows like the retail "VS. Mode" strip the keyboard tab replaces (the Friends tab looked small at 24)
TILED = m.TAB_W * 32 // 2


def tile(rows):
    nib = []
    for ty in range(0, 32, 8):
        for tx in range(0, m.TAB_W, 8):
            for y in range(8):
                for x in range(8):
                    yy = ty + y
                    nib.append(rows[yy][tx + x] if yy < m.TAB_H else 0)
    out = bytearray((nib[i] << 4) | nib[i + 1] for i in range(0, len(nib), 2))
    assert len(out) == TILED
    return bytes(out)


def header():
    out = ["/* Generated by tools/frd_tab_art.py. Do not edit; regenerate. Friends screen title tabs: 168 x 28 I4 in the retail GX tile order (%d bytes each). */" % TILED,
           "#define FRD_TAB_BYTES %d" % TILED]
    for name, text, base in STRIPS:
        b = tile(m.render_tab(text, base, 1.25, 0.32) if name == "friends" else m.render_tab(text, base))      # the keyboard tab heavier and slanted like Melee's strips
        out.append("static const unsigned char frd_tab_%s[FRD_TAB_BYTES] = {   /* %s */" % (name, text))
        for i in range(0, len(b), 24):
            out.append("    " + ", ".join("0x%02X" % v for v in b[i:i + 24]) + ",")
        out.append("};")
    return "\n".join(out) + "\n"


if __name__ == "__main__":
    here = os.path.dirname(os.path.abspath(__file__))
    o = sys.argv[1] if len(sys.argv) > 1 else os.path.join(here, "..", "offline", "multishine", "menus", "sign", "frd_tab_art.h")
    open(o, "w").write(header())
