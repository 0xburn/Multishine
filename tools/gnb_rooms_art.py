"""Game Night list header art: writes from rooms-beta-2's Rooms_gui.dat (attunegames/Ishiiruka, tag rooms-beta-2;
: free to use).  The three images replace, in RAM and with the same size and format, the Trophy Gallery's header labels and side label of TyMnView
(gnb_art.c): RoomsHeaderLeft_image ("Online Play", 168x28 I4), RoomsHeaderRight_image ("Rooms", 168x28 I4), RoomsSideLabel_image ("PUBLIC", 160x12 IA4), PackBits-packed (2.8 KB for 7.3 KB).
The header is generated at build time into the build's work directory (sg_ovl_pack.py) and never stored in the repository.

  gnb_rooms_art.py ROOMS_GUI.dat           exit 0 written, 2 the file is not the expected one
  gnb_rooms_art.py --find                       prints the Rooms_gui.dat the build would use (GNB_ROOMS_GUI, else the extracted rooms-beta-2 tree), exit 1 if none
"""
import os, struct, sys

WANT = (("RoomsHeaderLeft_image", "GNB_RA_LEFT", 168, 28, 0), ("RoomsHeaderRight_image", "GNB_RA_RIGHT", 168, 28, 0), ("RoomsSideLabel_image", "GNB_RA_SIDE", 160, 12, 2))
REL = ".analysis-deps/work/rooms_beta2/src/x/Ishiiruka-rooms-beta-2/Data/Sys/GameFiles/GALE01/Rooms_gui.dat"


def size_of(w, h, fmt):
    bw, bh, bpp = {0: (8, 8, 4), 2: (8, 4, 8)}[fmt]
    return ((w + bw - 1) // bw) * ((h + bh - 1) // bh) * bw * bh * bpp // 8


def images(path):
    b = open(path, "rb").read()
    fsize, dsize, nrel, npub, next_ = struct.unpack(">5I", b[:20])
    d = b[0x20:0x20 + dsize]
    pt = 0x20 + dsize + 4 * nrel
    st = pt + 8 * (npub + next_)
    pub = {}
    for i in range(npub):
        o, so = struct.unpack(">2I", b[pt + 8 * i:pt + 8 * i + 8])
        pub[b[st + so:b.index(b"\0", st + so)].decode()] = o
    out = []
    for name, cname, w, h, fmt in WANT:
        o = pub.get(name)
        if o is None:
            raise ValueError("no %s" % name)
        data, iw, ih, ifmt = struct.unpack(">IHHI", d[o:o + 12])
        if (iw, ih, ifmt) != (w, h, fmt):
            raise ValueError("%s is %dx%d format %d" % (name, iw, ih, ifmt))
        out.append((cname, d[data:data + size_of(w, h, fmt)]))
    return out


def packbits(d):
    """PackBits as gnb_art.c unpack: header h < 128 = h + 1 literal bytes follow; h >= 128 = the next byte repeated h - 126 times (3..129)"""
    out, lit, i = bytearray(), bytearray(), 0
    def flush():
        while lit:
            c = lit[:128]
            out.append(len(c) - 1); out.extend(c)
            del lit[:128]
    while i < len(d):
        j = i
        while j < len(d) and d[j] == d[i] and j - i < 129:
            j += 1
        if j - i >= 3:
            flush(); out.append(126 + j - i); out.append(d[i]); i = j
        else:
            lit.append(d[i]); i += 1
    flush()
    return bytes(out)


def unpackbits(p, n):
    o, i = bytearray(), 0
    while len(o) < n:
        h = p[i]; i += 1
        if h < 128:
            o += p[i:i + h + 1]; i += h + 1
        else:
            o += bytes([p[i]]) * (h - 126); i += 1
    return bytes(o)


def find():
    env = os.environ.get("GNB_ROOMS_GUI")
    if env:
        return env if os.path.isfile(env) else None
    here = os.path.dirname(os.path.abspath(__file__))
    repo = os.path.dirname(here)
    cands = [os.path.join(repo, REL)]
    for c in cands:
        if os.path.isfile(c):
            return c
    return None


def main(argv):
    if argv[:1] == ["--find"]:
        p = find()
        if p:
            print(p)
        return 0 if p else 1
    src, dst = argv
    try:
        imgs = images(src)
    except (ValueError, struct.error, OSError) as e:
        sys.stderr.write("gnb_rooms_art: %s\n" % e)
        return 2
    with open(dst, "w") as f:
        f.write("/* generated by tools/gnb_rooms_art.py from rooms-beta-2 Rooms_gui.dat (attunegames/Ishiiruka); not stored in the repository */\n")
        for cname, data in imgs:
            pk = packbits(data)
            assert unpackbits(pk, len(data)) == data
            f.write("#define %s_N %du             /* unpacked bytes (the retail image of the same size and format) */\n" % (cname, len(data)))
            f.write("static const unsigned char %s[%d] = {     /* PackBits */\n" % (cname, len(pk)))
            for i in range(0, len(pk), 24):
                f.write("  " + ",".join("0x%02X" % x for x in pk[i:i + 24]) + ",\n")
            f.write("};\n")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
