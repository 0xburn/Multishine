"""Menu label table and title tab texts.
Plate labels (176 x 30 IA4) are not rendered here any more: the generated header lists the label texts and the engine composes the letters from Melee's own menu
font at run time.  The title tab strips (168 x 28 I4, italic) are still our own rendering with an open font (Aileron, bundled with Pillow).

  python3 tools/menu_label_art.py header NAME=Text ... --out ml_tex.h      C table
"""
import sys

from PIL import Image, ImageDraw, ImageFont

W, H = 176, 30
SS = 4                       # supersampling (title tabs)


def _font(px):
    return ImageFont.load_default(px)


TAB_W, TAB_H = 168, 28
TABS = [("slippi", "Slippi"), ("main", "Main Menu"), ("more", "More"), ("orig", "Original menu"), ("grand", "Standings"), ("friends", "Friends")]     # "more" = the More screen's tab; title tab texts: Slippi's screen, the parent tab of the first level and More


def render_tab(text, base=24, stroke_px=0.75, shear=0.25):
    """The title tab strip texture (I4: 4 bit intensity, white italic letters, no outline; 168 x 28): rows of 4 bit values."""
    size = base * SS
    f = _font(size)
    stroke = int(stroke_px * SS)
    while True:
        l, t, r, b = f.getbbox(text, stroke_width=stroke)
        if (r - l) / SS <= TAB_W - 24 or size <= 12 * SS:
            break
        size -= SS
        f = _font(size)
    w, h = r - l, b - t
    big = Image.new("L", (TAB_W * SS, TAB_H * SS), 0)
    ImageDraw.Draw(big).text(((TAB_W * SS - w) // 2 - l, (TAB_H * SS - h) // 2 - t - SS), text, font=f, fill=255, stroke_width=stroke, stroke_fill=255)
    big = big.transform(big.size, Image.AFFINE, (1, shear, -shear * TAB_H * SS / 2, 0, 1, 0), Image.BILINEAR)
    small = big.resize((TAB_W, TAB_H), Image.BOX).load()
    return [[min(15, (small[x, y] * 15 + 127) // 255) for x in range(TAB_W)] for y in range(TAB_H)]


def pack_tab(rows):
    flat = [v for r in rows for v in r]
    return bytes((flat[i] << 4) | flat[i + 1] for i in range(0, len(flat), 2))


def header(items):
    out = ["/* Generated by tools/menu_label_art.py. Do not edit; regenerate. Plate labels: the text only; the letters are composed at run time from Melee's own menu font (ml_font_label in ml_core.c). */",
           "#define ML_TEX_W %d" % W, "#define ML_TEX_H %d" % H, "#define ML_NTEX %d" % len(items)]
    out.append("static const char *const ml_tex_names[ML_NTEX] = {")
    for name, text in items:
        out.append('    "%s",   /* %s */' % (text, name))
    out.append("};")
    out += ["#define ML_TAB_W %d" % TAB_W, "#define ML_TAB_H %d" % TAB_H, "#define ML_TAB_BYTES %d" % (TAB_W * TAB_H // 2), "#define ML_NTAB %d" % len(TABS),
            "/* title tab texts: composed at run time from Melee's own menu font too (ml_font_to_i4 in ml_core.cthe same font as the retail menu everywhere, no strip art stored) */",
            "static const char *const ml_tab_names[ML_NTAB] = {"]
    for name, text in TABS:
        out.append('    "%s",   /* %s */' % (text, name))
    out.append("};")
    return "\n".join(out) + "\n"


if __name__ == "__main__":
    if sys.argv[1] == "header":
        a = sys.argv[2:]
        o = a[a.index("--out") + 1]
        items = [x.split("=", 1) for x in a[:a.index("--out")]]
        open(o, "w").write(header(items))
