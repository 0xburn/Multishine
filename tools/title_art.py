"""title_art: docs/data/title_text.json (the wording and the place of OUR line on the title screen) -> offline/multishine/menus/tt/tt_text.h
.

  python3 tools/title_art.py [--check] [--preview OUT.png]

Generated: the line (text, cap height, row), the layout numbers (centre column, logo gap, fade frames), our own logo (the Multishine mark, the five open hexagons of
 _MARK, rasterised here to 4 bit coverage; our own art, so it may live in the repo), the fade table and the vertex values as float bit patterns
(the console build has no FPU code): the retail corners of the notice quad (only CHECKED by the console glue, never written) and the fixed place of our own copy of it.
Nothing of Nintendo's is read or written here.  --check: exit 1 when tt_text.h differs.
--preview: the logo alone, enlarged (the full line needs the game's font: see the host test's TT_PREVIEW)."""
import argparse, json, math, os, struct, sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(HERE)
SRC = os.path.join(REPO, "docs/data/title_text.json")
OUT = os.path.join(REPO, "offline/multishine/menus/tt/tt_text.h")
sys.path.insert(0, HERE)

CHARSET = set("ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789 ") | set(",.:;?!^_/~|'\"()[]{}+-=<>$%#&*@")
# the retail quads (GmTtAll.usd, TtlMoji_Top_joint, read with the study script; the console glue checks these exact values before writing)
J6_TOP, J6_BOT, J6_X = 2.399902105331421, -2.0, 23.56005859375       # notice quad: 496 x 48 texels over 4.4 units
J7_Y, J7_XL, J7_XR = 0.5, -10.639892578125, 10.1650390625              # "INTELLIGENT SYSTEMS" quad, 224 x 12
RETAIL_ROWS = 48


def f32(v):
    return struct.unpack(">I", struct.pack(">f", v))[0]


NIB_OFF = 11      # the OFFLINE level of the mark in 4 bit levels (ml_mark_level.h MKL_NIB_OFF; the same 11/15 as the menus' alpha 187/255): the title dims by the material tint of the mark quad (grey 187), no second image


def logo_bits(w, h, stroke_scale, top=15, fade=None):
    """the mark, fitted into w x h, 4 bit coverage x opacity: from tools/brand/make_ui_mark.py fit, the ONE source of the mark (title, Melee menus, Settings pages)"""
    sys.path.insert(0, os.path.join(HERE, "brand"))
    import make_ui_mark as M
    img = M.fit(w, h, stroke_scale, fade=fade)
    return [[min(top, int(round(v * top))) for v in row] for row in img]


def build(src=SRC):
    with open(src) as f:
        c = json.load(f)
    if c.get("format") != "multishine-title-text" or c.get("version") != 1:
        raise SystemExit("%s: not a multishine-title-text v1 file" % src)
    L = c["layout"]
    lines = c["lines"]
    if not 1 <= len(lines) <= 8:
        raise SystemExit("1 to 8 lines")
    IH = 48
    for ln in lines:
        bad = sorted(set(ln["text"]) - CHARSET)
        if bad:
            raise SystemExit("line %r: characters the menu font path cannot draw: %r" % (ln["id"], "".join(bad)))
        if not ln["text"].strip() or len(ln["text"]) > 96:
            raise SystemExit("line %r: empty or longer than 96 characters" % ln["id"])
        if not 5 <= ln["cap"] <= 16 or ln["y"] + ln["cap"] > IH:
            raise SystemExit("line %r: cap 5..16 and inside the %d image rows" % (ln["id"], IH))
    lg = L["logo"]
    if lg["w"] % 2 or lg["x"] + lg["w"] > 496 or lg["y"] + lg["h"] > IH:
        raise SystemExit("logo outside the image")
    if L["text_x"] + L["text_w"] > 496:
        raise SystemExit("text band wider than the image")
    centre = int(L.get("centre", 0))
    if not 0 <= centre <= 496:
        raise SystemExit("centre 0..496")
    fade = int(L.get("fade_frames", 0))
    if not 0 <= fade <= 120:
        raise SystemExit("fade_frames 0..120 (0 = off)")
    pos = L["position"]
    bits = logo_bits(lg["w"], lg["h"], lg.get("stroke_scale", 1.0))
    import make_ui_mark as M2
    fo = logo_bits(lg["w"], lg["h"], lg.get("stroke_scale", 1.0), fade=M2.FADEOFF)      # the cyan state's fade-off variant (MARK_BLUE_FADEOFF)
    vals = {"TT_J6_YTOP": f32(J6_TOP), "TT_J6_YBOT": f32(J6_BOT), "TT_J6_XR": f32(J6_X), "TT_J6_XL": f32(-J6_X),
            "TT_POS_X": f32(pos["x"]), "TT_POS_Y": f32(pos["y"]), "TT_POS_Z": f32(pos["z"])}
    o = ["/* GENERATED by tools/title_art.py from docs/data/title_text.json: do not edit (edit the json, then run the tool; the host test checks it) */",
         "#ifndef TT_TEXT_H", "#define TT_TEXT_H", "#include \"tt_core.h\"",
         "#define TT_TEXT_X %d" % L["text_x"], "#define TT_TEXT_W %d" % L["text_w"], "#define TT_CENTRE %d" % centre,
         "#define TT_LOGO_W %d" % lg["w"], "#define TT_LOGO_H %d" % lg["h"], "#define TT_LOGO_X %d" % lg["x"], "#define TT_LOGO_Y %d" % lg["y"],
         "#define TT_LOGO_GAP %d" % lg.get("gap", 8), "#define TT_FADE_N %d" % fade,
         "#define TT_RIGHT_CAP %d" % L["right"]["cap"], "#define TT_RIGHT_Y %d" % L["right"]["y"], "#define TT_RIGHT_EDGE %d" % L["right"]["edge"]]
    o += ["/* vertex values (float bit patterns): the retail corners of the notice quad the glue checks (the quad is never written), and the fixed place of our own copy of it (joint position, world units) */"]
    o += ["#define %s 0x%08Xu" % (k, v) for k, v in vals.items()]
    # the fade: material alpha of our quad, float bit patterns, ease-out from 0 to the retail 0.999 (one entry per frame, TT_FADE_N + 1 entries)
    o += ["/* the fade-in: material alpha per frame (ease-out, 0 to 0.999), float bit patterns; TT_FADE_N = 0: no fade */", "static const unsigned int tt_fade[%d] = {" % (fade + 1)]
    fv = [f32(0.999 * (1.0 - (1.0 - i / float(fade)) ** 2)) if fade else f32(0.999) for i in range(fade + 1)]
    for i in range(0, len(fv), 6):
        o.append("    " + ", ".join("0x%08Xu" % v for v in fv[i:i + 6]) + ",")
    o += ["};"]
    o += ["#define TT_NLINES %d" % len(lines), "static const struct tt_line tt_lines[TT_NLINES] = {"]
    o += ["    { %s, %d, %d },        /* %s */" % (json.dumps(ln["text"]), ln["cap"], ln["y"], ln["id"]) for ln in lines]
    o += ["};", "/* the Multishine mark, %d x %d, 4 bit coverage, two texels per byte (left in the high nibble) */" % (lg["w"], lg["h"]),
          "static const unsigned char tt_logo[%d] = {" % (lg["w"] * lg["h"] // 2)]
    def pack(b):
        flat = []
        for row in b:
            for i in range(0, len(row), 2):
                flat.append((row[i] << 4) | row[i + 1])
        for i in range(0, len(flat), 24):
            o.append("    " + ", ".join("0x%02X" % x for x in flat[i:i + 24]) + ",")
    pack(bits)
    o += ["};", "/* the same mark with the pairs of hexagons at 100 / 70 / 40 percent: the cyan state when MARK_BLUE_FADEOFF is 1 (ml_mark_level.h) */",
          "#ifndef MARK_BLUE_FADEOFF", "#define MARK_BLUE_FADEOFF 0", "#endif", "#if MARK_BLUE_FADEOFF",
          "static const unsigned char tt_logo_fo[%d] = {" % (lg["w"] * lg["h"] // 2)]
    pack(fo)
    o += ["};", "#endif", "#endif", ""]
    return "\n".join(o), bits


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--preview")
    a = ap.parse_args(argv)
    text, bits = build()
    if a.check:
        cur = open(OUT).read() if os.path.exists(OUT) else ""
        if cur != text:
            print("%s is out of date: run python3 tools/title_art.py" % os.path.relpath(OUT, REPO))
            return 1
        print("tt_text.h up to date")
        return 0
    open(OUT, "w").write(text)
    print("wrote", os.path.relpath(OUT, REPO))
    if a.preview:
        from PIL import Image
        h, w = len(bits), len(bits[0])
        im = Image.new("L", (w, h))
        im.putdata([v * 17 for row in bits for v in row])
        im.resize((w * 8, h * 8), Image.NEAREST).save(a.preview)
    return 0


if __name__ == "__main__":
    sys.exit(main())
